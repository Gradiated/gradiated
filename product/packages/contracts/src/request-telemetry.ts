import { z } from "@hono/zod-openapi";

const count = z.number().int().min(0).max(Number.MAX_SAFE_INTEGER);
const role = z.enum([
  "system",
  "developer",
  "user",
  "assistant",
  "tool",
  "other",
  "none",
]);
const roleCounts = z.strictObject({
  system: count,
  developer: count,
  user: count,
  assistant: count,
  tool: count,
  other: count,
});
const schemaCounts = z.strictObject({
  nodes: count.max(4096),
  properties: count,
  required: count,
  enum_values: count,
  max_depth: count.max(32),
  truncated: z.boolean(),
});
const tokenBucket = z.enum([
  "0",
  "1_128",
  "129_512",
  "513_2048",
  "2049_8192",
  "8193_32768",
  "32769_131072",
  "131073_524288",
  "524289_plus",
]);
const ratioBucket = z.enum([
  "undefined",
  "0",
  "0_0.1",
  "0.1_0.25",
  "0.25_0.5",
  "0.5_1",
  "1",
  "1_4",
  "4_plus",
]);

export const RequestTelemetrySchema = z
  .strictObject({
    schema_version: z.literal(1),
    protocol: z.enum([
      "openai_chat",
      "openai_responses",
      "anthropic_messages",
      "system_one",
    ]),
    client: z.enum([
      "other",
      "claude-code",
      "opencode",
      "codex",
      "openai-python",
      "openai",
      "openai-node",
      "anthropic-python",
      "anthropic",
      "anthropic-node",
      "curl",
    ]),
    traffic: z.enum(["routed", "verification"]),
    kind: z.enum([
      "plain_text",
      "tool_context",
      "structured_output",
      "multimodal",
      "system_one",
    ]),
    task_type: z.enum([
      "unknown",
      "other",
      "code_edit",
      "code_generation",
      "debugging",
      "summarization",
      "translation",
      "extraction",
      "classification",
      "reasoning",
      "question_answering",
      "creative_writing",
    ]),
    task_source: z.enum(["unknown", "caller", "heuristic"]),
    task_scan_bytes: count.max(8192),
    task_scan_truncated: z.boolean(),
    language_hint: z.enum([
      "unknown",
      "python",
      "typescript",
      "javascript",
      "rust",
      "go",
      "java",
      "sql",
      "shell",
      "c_cpp",
      "json",
      "html_css",
    ]),
    text_shape: z.strictObject({
      scanned_bytes: count.max(65536),
      line_breaks: count,
      whitespace_bytes: count,
      digit_bytes: count,
      non_ascii_bytes: count,
      code_fences: count,
      max_line_bytes: count.max(65536),
      truncated: z.boolean(),
    }),
    token_buckets: z
      .strictObject({
        input: tokenBucket,
        uncached_input: tokenBucket,
        output: tokenBucket,
        cache_fraction: ratioBucket,
        output_input_ratio: ratioBucket,
        reasoning_fraction: ratioBucket,
      })
      .nullable(),
    request_bytes: count,
    messages: count,
    roles: roleCounts,
    text_bytes: roleCounts,
    content_parts: z.strictObject({
      text: count,
      image: count,
      audio: count,
      video: count,
      file: count,
      other: count,
    }),
    max_message_text_bytes: count,
    instruction_text_bytes: count,
    last_role: role,
    role_transitions: count,
    last_user_text_bytes: count,
    tool_definitions: count,
    strict_tools: count,
    tool_calls: count,
    tool_results: count,
    tool_argument_text_bytes: count,
    tool_choice: z.enum([
      "unspecified",
      "auto",
      "none",
      "required",
      "named",
      "other",
    ]),
    tool_schema: schemaCounts,
    response_format: z.enum([
      "unspecified",
      "text",
      "json_object",
      "json_schema",
      "other",
    ]),
    response_schema: schemaCounts,
    reasoning_effort: z.enum([
      "unspecified",
      "none",
      "minimal",
      "low",
      "medium",
      "high",
      "xhigh",
      "max",
      "numeric",
      "other",
    ]),
    thinking_mode: z.enum([
      "unspecified",
      "enabled",
      "disabled",
      "adaptive",
      "other",
    ]),
    thinking_budget: count.nullable(),
    requested_max_output_tokens: count.nullable(),
    effective_max_output_tokens: count.nullable(),
    output_limit_source: z.enum([
      "unknown",
      "caller",
      "catalog",
      "remaining_context",
    ]),
    context_limit_tokens: count.nullable(),
    sampling: z.strictObject({
      temperature: z.number().finite().min(0).max(2).nullable(),
      top_p: z.number().finite().min(0).max(1).nullable(),
      top_k: z.number().int().min(-1).max(1000000).nullable(),
      min_p: z.number().finite().min(0).max(1).nullable(),
      frequency_penalty: z.number().finite().min(-2).max(2).nullable(),
      presence_penalty: z.number().finite().min(-2).max(2).nullable(),
      repetition_penalty: z.number().finite().min(0).max(10).nullable(),
      candidates: count.max(128).nullable(),
      seed_present: z.boolean(),
      stop_sequences: count,
      logprobs_requested: z.boolean(),
      parallel_tool_calls: z.boolean().nullable(),
    }),
    truncated: z.boolean(),
  })
  .openapi("RequestTelemetry");

export type RequestTelemetry = z.infer<typeof RequestTelemetrySchema>;
