import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

import { createOpenApiDocuments } from "../src/openapi.js";

const documents = createOpenApiDocuments();

// Lets clients such as the MCP server check at compile time that they cover every operation.
const operationIds = (document: typeof documents.client) =>
  Object.values(document.paths ?? {})
    .flatMap((item) =>
      Object.values(item ?? {}).flatMap((operation) =>
        typeof operation === "object" &&
        operation !== null &&
        "operationId" in operation &&
        typeof operation.operationId === "string"
          ? [operation.operationId]
          : [],
      ),
    )
    .sort();

const operationIdTypes = (ids: string[]) =>
  [
    "// Generated by scripts/generate-openapi.ts from the client OpenAPI document.",
    "export type OperationId =",
    ...ids.map((id) => `  | ${JSON.stringify(id)}`),
  ].join("\n") + ";\n";

const outputs = [
  {
    path: "../generated/openapi.json",
    serialized: `${JSON.stringify(documents.public, null, 2)}\n`,
  },
  {
    path: "../generated/client-openapi.json",
    serialized: `${JSON.stringify(documents.client, null, 2)}\n`,
  },
  {
    path: "../generated/operation-ids.d.ts",
    serialized: operationIdTypes(operationIds(documents.client)),
  },
];

for (const output of outputs) {
  const outputPath = resolve(import.meta.dirname, output.path);
  const { serialized } = output;

  if (!process.argv.includes("--check")) {
    await writeFile(outputPath, serialized, "utf8");
    continue;
  }

  const existing = await readFile(outputPath, "utf8").catch(() => "");
  if (existing !== serialized) {
    console.error(
      `${output.path.slice(3)} is stale; run pnpm --filter @gradiated/api openapi:generate`,
    );
    process.exitCode = 1;
  }
}
