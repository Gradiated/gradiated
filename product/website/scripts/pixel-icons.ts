/** Each square is sampled at this many pixels a side. */
const SAMPLE = 12;

const OUTPUT = new URL(
  "../src/components/design/pixel-icons.generated.ts",
  import.meta.url,
);

const require = createRequire(import.meta.url);

const pixelate = async (svg: Buffer, grid: number): Promise<string> => {
  const size = grid * SAMPLE;
  const { data } = await sharp(svg, { density: 72 * (size / 256) })
    .resize(size, size)
    .ensureAlpha()
    .extractChannel("alpha")
    .raw()
    .toBuffer({ resolveWithObject: true });

  let path = "";
  for (let y = 0; y < grid; y++) {
    let run = -1;
    for (let x = 0; x <= grid; x++) {
      let alpha = 0;
      if (x < grid) {
        for (let sy = 0; sy < SAMPLE; sy++) {
          for (let sx = 0; sx < SAMPLE; sx++) {
            alpha += data[(y * SAMPLE + sy) * size + x * SAMPLE + sx];
          }
        }
      }

      const filled = alpha / (SAMPLE * SAMPLE * 255) >= THRESHOLD;
      if (filled && run < 0) run = x;
      if (!filled && run >= 0) {
        path += `M${run} ${y}h${x - run}v1h-${x - run}z`;
        run = -1;
      }
    }
  }

  return path;
};

const lines: string[] = [];
for (const [name, { grid, source, weight = "bold" }] of Object.entries(ICONS)) {
  const file = require.resolve(
    `@phosphor-icons/core/assets/${weight}/${weight === "regular" ? source : `${source}-${weight}`}.svg`,
  );
  const d = await pixelate(await readFile(file), grid);
  lines.push(
    `  ${JSON.stringify(name)}: { d: ${JSON.stringify(d)}, grid: ${grid} },`,
  );
}

await writeFile(
  OUTPUT,
  `// Generated by scripts/pixel-icons.ts from Phosphor (MIT, phosphoricons.com).
// Do not edit; change the script and run \`pnpm icons:pixel\`.

export const PIXEL_ICONS = {
${lines.join("\n")}
} as const;
`,
);
