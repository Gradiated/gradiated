import type { Story, StoryCover, StoryArt } from "./components/design";
import { articles } from "./articles";
import { handbookPages } from "./handbook";
import { handbookArt, handbookCovers } from "./handbook-visuals";
import { artworkPresets } from "./lib/artwork";

/**
 * The Library's catalogue, shaped into cards.
 *
 * It lives here rather than in the Library page because it is not the Library
 * page's: the hardware hero shows three of these pieces, and building them a
 * second time there is how the same article ends up with two different
 * standfirsts. One place turns a catalogue entry into a card.
 */

/* Handbook dates are intentionally shared until the catalogue carries dates in
   its own catalogue. Notes always use their authored article metadata. */
const HANDBOOK_DATE = { date: "Sep 9, 2026", dateTime: "2026-09-09" };

const displayDate = (date: string): string =>
  new Date(date).toLocaleDateString("en-US", {
    day: "numeric",
    month: "short",
    year: "numeric",
  });

/* The excerpt is the piece's own opening, read from the MDX at build time
   rather than written a second time here. A summary maintained beside the
   thing it summarises drifts from it — this cannot. */
const bodies = import.meta.glob("../handbook/*.mdx", {
  eager: true,
  import: "default",
  query: "?raw",
}) as Record<string, string>;

/** How much of the opening a card shows before trailing off. */
const EXCERPT_CHARS = 190;

/** Collapse whitespace and cut at a word, never mid-syllable. */
const trim = (prose: string): string | undefined => {
  const flat = prose.replace(/\s+/g, " ").trim();
  if (!flat) return undefined;
  if (flat.length <= EXCERPT_CHARS) return flat;
  const cut = flat.slice(0, EXCERPT_CHARS);
  return `${cut.slice(0, cut.lastIndexOf(" "))}…`;
};

const excerptFor = (slug: string): string | undefined => {
  const raw = bodies[`../handbook/${slug}.mdx`];
  if (!raw) return undefined;

  const prose = raw
    // Headings, list markers and emphasis are structure, not sentence.
    .replace(/^#{1,6}\s+.*$/gm, "")
    .replace(/^[-*]\s+/gm, "")
    .replace(/[*_`]/g, "")
    // Links keep their text and lose their target.
    .replace(/\[([^\]]+)\]\([^)]*\)/g, "$1")
    .split(/\n{2,}/)
    .map((block) => block.replace(/\s+/g, " ").trim())
    .filter(Boolean)
    .join(" ");

  return trim(prose);
};

/* Covers are generated by the same wafer engine exposed at /artwork-generator/.
   The catalogue stores presets, not image crops, so every size is rendered at
   its own pixel density and remains sharp. */
/* Real artwork, delivered in the two crops the layout uses (0.89 portrait
   and the lead/pair landscape). Pieces without an entry keep their generated
   wafer cover — the maps below stay as the fallback, not a competitor. */
const NOTE_ART: Record<string, StoryArt> = {
  "/library/gemma-inference-engine/": {
    tall: "/brand/library/carat.webp",
    wide: "/brand/library/carat-wide.webp",
  },
  "/notes/our-thesis/": {
    tall: "/brand/library/thesis.webp",
    wide: "/brand/library/thesis-wide.webp",
  },
  "/notes/2026-10-starting-on-hard-mode/": {
    tall: "/brand/library/mission.webp",
    wide: "/brand/library/mission-wide.webp",
  },
};

const NOTE_COVERS: Record<string, StoryCover> = {
  "/library/gemma-inference-engine/": artworkPresets.carat,
  "/notes/our-thesis/": artworkPresets.thesis,
};

/** Newest first, with the collection supplied by article metadata. */
const writing: Story[] = articles
  .filter((article) => article.collection === "library")
  .map((article) => ({
    art: NOTE_ART[article.path],
    cover: NOTE_COVERS[article.path],
    /* Drafts carry their authored date too — they only list in dev,
       and a dateless card reads as a bug rather than a status. */
    date: displayDate(article.publishedAt),
    dateTime: article.status === "draft" ? undefined : article.publishedAt,
    href: article.path,
    kind: "note",
    lede: article.description,
    title: article.title,
  }));

/* Handbook keeps its authored order rather than being sorted,
   and its sequence is an argument — mission, then product, then people. */
const handbook: Story[] = handbookPages.map((page) => ({
  ...HANDBOOK_DATE,
  art: handbookArt[page.slug],
  cover: handbookCovers[page.slug],
  excerpt: excerptFor(page.slug),
  /* Brand leads to the living reference, not prose about it: the style
     page IS the brand documentation. The MDX page stays routed but
     unlisted (parked). */
  href: page.slug === "brand" ? "/style/" : `/handbook/${page.slug}/`,
  kind: "handbook" as const,
  title: page.title,
}));

/** Newest note first, then Handbook entries in their authored order. */
export const libraryStories: Story[] = [...writing, ...handbook];

/** One piece, by the path it lives at. Returns nothing if it has moved. */
export const storyAt = (href: string): Story | undefined =>
  libraryStories.find((story) => story.href === href);
