# --------------------------------------------------------------------------------------------- download


def _get(url: str, timeout: float = 120) -> Any:
    request = urllib.request.Request(url, headers={"User-Agent": USER_AGENT})
    return urllib.request.urlopen(request, timeout=timeout)  # noqa: S310 - fixed https host


def _json(url: str) -> Any:
    for attempt in range(5):
        try:
            with _get(url, timeout=60) as response:
                return json.load(response)
        except (urllib.error.URLError, TimeoutError):
            if attempt == 4:
                raise
            time.sleep(2**attempt)
    raise AssertionError


def repo_info(repo: str, revision: str | None) -> dict[str, Any]:
    url = f"{HF}/api/datasets/{repo}"
    if revision:
        url += f"/revision/{revision}"
    return _json(url + "?blobs=true")


def fetch(repo: str, revision: str, sibling: dict[str, Any], raw: Path) -> Path:
    """Download one repo file at ``revision`` into ``raw`` (cached); verify size and LFS sha256."""
    name = sibling["rfilename"]
    path = raw / name
    size = sibling.get("size")
    if path.exists() and (size is None or path.stat().st_size == size):
        return path
    path.parent.mkdir(parents=True, exist_ok=True)
    url = f"{HF}/datasets/{repo}/resolve/{revision}/{urllib.parse.quote(name)}"
    want = (sibling.get("lfs") or {}).get("sha256")
    for attempt in range(5):
        part = path.with_name(path.name + ".part")
        digest = hashlib.sha256()
        try:
            with _get(url, timeout=300) as response, part.open("wb") as handle:
                while chunk := response.read(1 << 20):
                    handle.write(chunk)
                    digest.update(chunk)
        except (urllib.error.URLError, TimeoutError, ConnectionError) as error:
            print(f"  retry {name}: {error}", file=sys.stderr)
            time.sleep(2**attempt)
            continue
        if size is not None and part.stat().st_size != size:
            print(f"  size mismatch {name}", file=sys.stderr)
            continue
        if want and digest.hexdigest() != want:
            print(f"  sha256 mismatch {name}", file=sys.stderr)
            continue
        part.rename(path)
        return path
    raise RuntimeError(f"could not download {repo}@{revision}/{name}")


@dataclass
class Fetched:
    source: Source
    revision: str
    head: str | None
    files: list[Path]
    file_meta: list[dict[str, Any]]
    docs: dict[str, str]
    card_license: Any


def fetch_source(source: Source, out: Path, latest: bool = False) -> Fetched:
    head = repo_info(source.repo, None)
    revision = head["sha"] if latest else source.revision
    info = head if latest else repo_info(source.repo, revision)
    if info.get("sha") != revision:
        raise RuntimeError(f"{source.repo}: API returned sha {info.get('sha')} for {revision}")
    raw = out / "_raw" / source.slug / revision
    siblings = {s["rfilename"]: s for s in info["siblings"]}
    pattern = re.compile(source.files)
    data = sorted(name for name in siblings if pattern.match(name))
    if not data:
        raise RuntimeError(f"{source.repo}: no files match {source.files}")
    docs = {}
    for name in source.docs:
        if name in siblings:
            docs[name] = hashlib.sha256(fetch(source.repo, revision, siblings[name], raw).read_bytes()).hexdigest()
    paths = []
    for name in data:
        print(f"  fetch {source.repo}/{name}", file=sys.stderr)
        paths.append(fetch(source.repo, revision, siblings[name], raw))
    meta = [
        {"file": n, "size": siblings[n].get("size"), "sha256": (siblings[n].get("lfs") or {}).get("sha256")}
        for n in data
    ]
    card = (info.get("cardData") or {}).get("license")
    return Fetched(source, revision, head["sha"], paths, meta, docs, card)


# --------------------------------------------------------------------------------------------- targets and validation


class Drop(Exception):
    def __init__(self, reason: str):
        super().__init__(reason)
        self.reason = reason


def option_keys(question: dict[str, Any]) -> list[str]:
    """Option keys exactly as pplx_decider ``protocol.options`` returns them."""
    if question["type"] == "choice":
        return list(question["criteria"])
    if question["type"] == "score":
        return [str(i) for i in range(len(question["criteria"]))]
    return ["false", "true"]


def _is_content(value: Any) -> bool:
    if isinstance(value, str):
        return True
    if isinstance(value, (dict, list)):
        try:
            json.dumps(value)
        except (TypeError, ValueError):
            return False
        return True
    return False


def distribution(keys: list[str], probs: dict[str, Any]) -> str | dict[str, float]:
    """A hard key when one option holds all the mass, else a normalised dict of the nonzero entries."""
    allowed = set(keys)
    clean: dict[str, float] = {}
    for key, value in probs.items():
        if key not in allowed:
            raise Drop("target_key_not_an_option")
        if value is None:
            continue
        number = float(value)
        if not math.isfinite(number) or number < 0:
            raise Drop("target_not_finite_nonnegative")
        if number > 0:
            clean[key] = number
    total = sum(clean.values())
    if total <= 0:
        raise Drop("target_no_mass")
    best = max(clean, key=clean.__getitem__)
    if clean[best] / total >= 1 - 1e-9:
        return best
    return {key: round(value / total, 6) for key, value in clean.items()}


def probability(value: Any) -> float:
    if isinstance(value, bool):
        return float(value)
    number = float(value)
    if not math.isfinite(number) or not 0 <= number <= 1:
        raise Drop("noul_target_out_of_range")
    return number


def check_target(question: dict[str, Any], target: Any) -> str | None:
    keys = option_keys(question)
    if question["type"] == "noul":
        if isinstance(target, bool):
            return None
        if isinstance(target, (int, float)) and math.isfinite(target) and 0 <= target <= 1:
            return None
        return "noul_target_invalid"
    if isinstance(target, str):
        return None if target in keys else "target_key_not_an_option"
    if isinstance(target, dict) and target:
        if any(k not in keys for k in target):
            return "target_key_not_an_option"
        values = list(target.values())
        if any(not isinstance(v, (int, float)) or not math.isfinite(v) or v < 0 for v in values):
            return "target_not_finite_nonnegative"
        if abs(sum(values) - 1) > 1e-3:
            return "target_not_normalised"
        return None
    return "target_invalid"


def check_question(question: Any) -> str | None:
    """pplx_decider ``Encoder.validate`` rules for one question (plus content types)."""
    kind = question.get("type") if isinstance(question, dict) else None
    if kind not in QUESTION_TYPES:
        return "bad_type"
    criteria = question.get("criteria")
    if kind == "choice":
        if not isinstance(criteria, dict):
            return "choice_criteria_not_dict"
        if any(not isinstance(k, str) or not k.strip() for k in criteria):
            return "empty_option_key"
        if any(v is not None and not _is_content(v) for v in criteria.values()):
            return "bad_option_description"
    elif kind == "score":
        if not isinstance(criteria, list):
            return "score_criteria_not_list"
        if any(not _is_content(v) for v in criteria):
            return "bad_level_description"
    elif criteria is not None:
        if not isinstance(criteria, dict) or any(k not in ("true", "false") for k in criteria):
            return "noul_criteria_invalid"
    instructions = question.get("instructions")
    if instructions is not None and not _is_content(instructions):
        return "bad_instructions"
    count = len(option_keys(question))
    if not 1 <= count <= MAX_OPTIONS:
        return "too_many_options" if count > MAX_OPTIONS else "no_options"
    if kind == "score" and count < 2:
        return "score_fewer_than_two_levels"
    return None


def validate_row(row: dict[str, Any]) -> str | None:
    state = row.get("state")
    if state is None or not _is_content(state):
        return "bad_state"
    if isinstance(state, str) and not state.strip():
        return "empty_state"
    questions = row.get("questions")
    if not isinstance(questions, dict) or not questions:
        return "no_questions"
    for key, question in questions.items():
        if not isinstance(key, str) or not key:
            return "empty_question_id"
        if reason := check_question(question):
            return reason
    expected = row.get("expected")
    if not isinstance(expected, dict) or not expected:
        return "no_expected"
    for key, target in expected.items():
        if key not in questions:
            return "expected_key_not_a_question"
        if reason := check_target(questions[key], target):
            return reason
    for name in ("source", "license", "id"):
        if not isinstance(row.get(name), str) or not row[name]:
            return f"missing_{name}"
    return None


def clean_question(kind: str, instructions: Any, criteria: Any) -> dict[str, Any]:
    question: dict[str, Any] = {"type": kind}
    if instructions not in (None, ""):
        question["instructions"] = instructions
    if kind != "noul" or criteria:
        question["criteria"] = criteria
    return question


def parse_state(state: Any) -> Any:
    """JSON-object states become objects; lists are serialised to a JSON string; other text stays as is."""
    if isinstance(state, str):
        text = state.lstrip()
        if text.startswith("{"):
            try:
                value = json.loads(state)
            except ValueError:
                return state
            if isinstance(value, dict):
                return value
        return state
    if isinstance(state, dict):
        return state
    if isinstance(state, list):
        return json.dumps(state, ensure_ascii=False)
    raise Drop("bad_state")


def _text(value: Any) -> str:
    if value is None:
        return ""
    return value if isinstance(value, str) else json.dumps(value, ensure_ascii=False)


def char_length(row: dict[str, Any]) -> int:
    total = len(_text(row["state"]))
    for question in row["questions"].values():
        total += len(_text(question.get("instructions"))) + 20
        criteria = question.get("criteria")
        if isinstance(criteria, dict):
            total += sum(len(k) + len(_text(v)) + 4 for k, v in criteria.items())
        elif isinstance(criteria, list):
            total += sum(len(_text(v)) + 4 for v in criteria)
        else:
            total += 30
    return total


# --------------------------------------------------------------------------------------------- statistics


@dataclass
class Stats:
    input_rows: int = 0
    rows: int = 0
    dropped: Counter = field(default_factory=Counter)
    dropped_questions: Counter = field(default_factory=Counter)
    question_types: Counter = field(default_factory=Counter)
    label_kinds: Counter = field(default_factory=Counter)
    questions_per_row: Counter = field(default_factory=Counter)
    licenses: Counter = field(default_factory=Counter)
    tasks: Counter = field(default_factory=Counter)
    extra: dict[str, Counter] = field(default_factory=dict)
    lengths: list[int] = field(default_factory=list)

    def count(self, name: str, key: Any, n: int = 1) -> None:
        self.extra.setdefault(name, Counter())[str(key)] += n

    def add(self, row: dict[str, Any]) -> None:
        self.rows += 1
        self.questions_per_row[len(row["questions"])] += 1
        self.licenses[row["license"]] += 1
        self.tasks[str(row.get("meta", {}).get("task"))] += 1
        for key, question in row["questions"].items():
            self.question_types[question["type"]] += 1
            if key in row["expected"]:
                target = row["expected"][key]
                soft = isinstance(target, dict) or (
                    question["type"] == "noul" and not isinstance(target, bool) and target not in (0, 1)
                )
                self.label_kinds[f"{question['type']}:{'soft' if soft else 'hard'}"] += 1
            else:
                self.label_kinds[f"{question['type']}:unlabeled"] += 1
        self.lengths.append(char_length(row))

    def summary(self) -> dict[str, Any]:
        lengths = sorted(self.lengths)

        def pct(p: float) -> int:
            return round(lengths[min(len(lengths) - 1, int(p / 100 * len(lengths)))] / 4) if lengths else 0

        return {
            "input_rows": self.input_rows,
            "rows": self.rows,
            "questions": sum(self.question_types.values()),
            "dropped_rows": dict(self.dropped.most_common()),
            "dropped_questions": dict(self.dropped_questions.most_common()),
            "question_types": dict(self.question_types.most_common()),
            "label_kinds": dict(sorted(self.label_kinds.items())),
            "questions_per_row": {str(k): v for k, v in sorted(self.questions_per_row.items())},
            "token_estimate_chars_div_4": {
                "p50": pct(50), "p90": pct(90), "p95": pct(95), "p99": pct(99),
                "max": round(lengths[-1] / 4) if lengths else 0,
                "mean": round(sum(lengths) / len(lengths) / 4) if lengths else 0,
            },
            "row_licenses": dict(self.licenses.most_common()),
            "tasks": dict(self.tasks.most_common()),
            **{name: dict(counter.most_common()) for name, counter in sorted(self.extra.items())},
        }


Converter = Callable[[Fetched, Stats, "Context"], Iterator[dict[str, Any]]]


@dataclass
class Context:
    out: Path
    latest: bool
    cache: dict[str, Any] = field(default_factory=dict)

    def fetched(self, slug: str) -> Fetched:
        if slug not in self.cache:
            self.cache[slug] = fetch_source(SOURCES[slug], self.out, self.latest)
        return self.cache[slug]


# --------------------------------------------------------------------------------------------- converters


def _parquet_batches(paths: Iterable[Path], columns: list[str], batch_size: int = 4096) -> Iterator[dict[str, Any]]:
    import pyarrow.parquet as pq

    for path in paths:
        handle = pq.ParquetFile(path)
        for batch in handle.iter_batches(batch_size=batch_size, columns=columns):
            yield from batch.to_pylist()


def convert_procedural(fetched: Fetched, stats: Stats, ctx: Context) -> Iterator[dict[str, Any]]:
    source = f"{fetched.source.repo}/{fetched.source.config}"
    for record in _parquet_batches(fetched.files, ["id", "task", "level", "state", "questions", "answers"]):
        stats.input_rows += 1
        try:
            questions = json.loads(record["questions"])
            answers = json.loads(record["answers"])
            state = parse_state(record["state"])
        except (ValueError, TypeError, Drop):
            stats.dropped["unparseable"] += 1
            continue
        out_q, expected = {}, {}
        for key, raw in questions.items():
            try:
                question = clean_question(raw.get("type"), raw.get("instructions"), raw.get("criteria"))
                if reason := check_question(question):
                    raise Drop(reason)
                answer = answers.get(key)
                if not isinstance(answer, dict):
                    raise Drop("no_answer")
                if question["type"] == "noul":
                    target: Any = probability(answer["noul"])
                else:
                    target = distribution(option_keys(question), answer.get("probabilities") or {})
            except (Drop, KeyError, TypeError, ValueError) as error:
                stats.dropped_questions[getattr(error, "reason", "bad_answer")] += 1
                continue
            out_q[key], expected[key] = question, target
        if not out_q:
            stats.dropped["no_labeled_questions"] += 1
            continue
        yield {
            "state": state,
            "questions": out_q,
            "expected": expected,
            "source": source,
            "license": fetched.source.license,
            "id": record["id"],
            "meta": {"task": record["task"], "level": record["level"]},
        }


def single_question(
    question_raw: dict[str, Any], expected: Any, soft: Any, stats: Stats
) -> tuple[dict[str, Any], Any]:
    """Question and target of a one-question SN92 row; ``soft`` (target_probs) is preferred when it agrees."""
    kind = question_raw.get("type")
    criteria = question_raw.get("criteria")
    if kind == "noul" and isinstance(criteria, dict):
        criteria = {k: v for k, v in criteria.items() if k in ("true", "false")} or None
    question = clean_question(kind, question_raw.get("instructions"), criteria)
    if reason := check_question(question):
        raise Drop(reason)
    keys = option_keys(question)
    if kind == "noul":
        hard_map = {"true": True, "yes": True, "1": True, "false": False, "no": False, "0": False}
        if isinstance(expected, bool):
            hard = expected
        elif str(expected).strip().lower() in hard_map:
            hard = hard_map[str(expected).strip().lower()]
        else:
            raise Drop("noul_expected_unrecognised")
        target: Any = 1.0 if hard else 0.0
        if isinstance(soft, dict) and "true" in soft:
            try:
                p = probability(soft["true"])
                if (p > 0.5) == hard or p == 0.5:
                    target = p
                else:
                    stats.count("soft_disagrees_with_expected", kind)
            except (Drop, TypeError, ValueError):
                stats.count("soft_invalid", kind)
        return question, target
    if expected is None or isinstance(expected, bool):
        raise Drop("no_expected")
    hard_key = str(expected)
    if hard_key not in keys:
        raise Drop("expected_not_an_option")
    target = hard_key
    if isinstance(soft, dict) and soft:
        try:
            dist = distribution(keys, {str(k): v for k, v in soft.items()})
            best = dist if isinstance(dist, str) else max(dist, key=dist.__getitem__)
            if best == hard_key:
                target = dist
            else:
                stats.count("soft_disagrees_with_expected", kind)
        except (Drop, TypeError, ValueError):
            stats.count("soft_invalid", kind)
    return question, target


def _jsonl(path: Path) -> Iterator[str]:
    opener = gzip.open if path.suffix == ".gz" else open
    with opener(path, "rt", encoding="utf-8") as handle:
        yield from handle


def specialist_ids(ctx: Context) -> set[str]:
    if "spec_ids" not in ctx.cache:
        ids = set()
        for path in ctx.fetched("sn92-specialists").files:
            for line in _jsonl(path):
                try:
                    ids.add(json.loads(line)["id"])
                except (ValueError, KeyError, TypeError):
                    pass
        ctx.cache["spec_ids"] = ids
    return ctx.cache["spec_ids"]


def convert_generalist(fetched: Fetched, stats: Stats, ctx: Context) -> Iterator[dict[str, Any]]:
    source = f"{fetched.source.repo}/{fetched.source.config}"
    spec_ids = specialist_ids(ctx)
    for path in fetched.files:
        for line in _jsonl(path):
            stats.input_rows += 1
            try:
                record = json.loads(line)
                quality = record.get("quality") if isinstance(record.get("quality"), dict) else {}
                question, target = single_question(record["question"], record.get("expected"),
                                                   quality.get("target_probs"), stats)
                state = parse_state(record["state"])
            except (Drop, KeyError, TypeError, ValueError, AttributeError) as error:
                stats.dropped[getattr(error, "reason", "unparseable")] += 1
                continue
            ancestry = record.get("ancestry") if isinstance(record.get("ancestry"), dict) else {}
            generator = record.get("generator") if isinstance(record.get("generator"), dict) else {}
            meta = {
                "task": record.get("family"),
                "category": record.get("category"),
                "lane": record.get("lane"),
                "mix_tier": record.get("mix_tier"),
                "lang": record.get("lang"),
                "benchmark": record.get("benchmark"),
                "component": record.get("component"),
                "gold_basis": record.get("gold_basis"),
                "author_family": ancestry.get("author_family"),
                "generator_model": generator.get("model") or generator.get("writer") or generator.get("kind"),
                "cf_pair": ancestry.get("cf_pair"),
                "translation_of": ancestry.get("translation_of"),
            }
            source_row = ancestry.get("source_row")
            if record.get("id") in spec_ids or source_row in spec_ids:
                meta["duplicate_of"] = f"decisionmodels/sn92-specialists:{source_row or record.get('id')}"
                stats.count("flagged_duplicate_of", "sn92-specialists")
            stats.count("component", meta["component"])
            stats.count("benchmark_field", meta["benchmark"])
            stats.count("author_family", meta["author_family"])
            yield {
                "state": state,
                "questions": {"decision": question},
                "expected": {"decision": target},
                "source": source,
                "license": str(record.get("licence") or fetched.source.license),
                "id": str(record["id"]),
                "meta": {k: v for k, v in meta.items() if v is not None},
            }


def convert_specialists(fetched: Fetched, stats: Stats, ctx: Context) -> Iterator[dict[str, Any]]:
    root = ctx.out / "_raw" / fetched.source.slug / fetched.revision
    for path in fetched.files:
        rel = path.relative_to(root).as_posix()
        category = rel.split("/")[0]
        for line in _jsonl(path):
            stats.input_rows += 1
            try:
                record = json.loads(line)
                if record.get("split") not in (None, "train"):
                    raise Drop("not_train_split")
                question, target = single_question(record["question"], record.get("expected"),
                                                   record.get("target_probs"), stats)
                state = parse_state(record["state"])
            except (Drop, KeyError, TypeError, ValueError, AttributeError) as error:
                stats.dropped[getattr(error, "reason", "unparseable")] += 1
                continue
            provenance = record.get("provenance") if isinstance(record.get("provenance"), dict) else {}
            stats.count("files", rel)
            meta = {
                "task": record.get("family"),
                "category": category,
                "file": rel,
                "lang": record.get("lang"),
                "difficulty": record.get("difficulty"),
                "generator": provenance.get("generator"),
                "generator_model": provenance.get("writer"),
            }
            yield {
                "state": state,
                "questions": {"decision": question},
                "expected": {"decision": target},
                "source": f"{fetched.source.repo}/{category}",
                "license": str(record.get("license") or fetched.source.license),
                "id": str(record["id"]),
                "meta": {k: v for k, v in meta.items() if v is not None},
            }


def procedural_state_hashes(ctx: Context) -> set[bytes]:
    if "ptd_hashes" not in ctx.cache:
        hashes = set()
        for record in _parquet_batches(ctx.fetched("procedural-typed-decisions").files, ["state"]):
            hashes.add(hashlib.sha1(record["state"].encode()).digest())
        ctx.cache["ptd_hashes"] = hashes
    return ctx.cache["ptd_hashes"]


JEV_COLUMNS = ["state", "kind", "id", "options", "target", "question", "source", "variant", "split",
               "group_id", "question_id", "license", "license_use"]


def convert_jev(fetched: Fetched, stats: Stats, ctx: Context) -> Iterator[dict[str, Any]]:
    """Commercial-use rows only, regrouped by contiguous (group_id, state, source task) into multi-question rows."""
    ptd = procedural_state_hashes(ctx)
    seen_ids: set[str] = set()
    source = f"{fetched.source.repo}/{fetched.source.config}"

    def build(members: list[dict[str, Any]]) -> dict[str, Any] | None:
        first = members[0]
        questions, expected = {}, {}
        for member in members:
            kind = member["kind"]
            options = list(member["options"] or [])
            targets = list(member["target"] or [])
            try:
                if kind == "choice":
                    if len(set(options)) != len(options):
                        raise Drop("duplicate_options")
                    question = clean_question(kind, member["question"], {o: None for o in options})
                elif kind == "score":
                    question = clean_question(kind, member["question"], options)
                elif kind == "noul":
                    question = clean_question(kind, member["question"], None)
                else:
                    raise Drop("bad_type")
                if reason := check_question(question):
                    raise Drop(reason)
                if kind == "noul":
                    if len(targets) != 1:
                        raise Drop("noul_target_shape")
                    target: Any = probability(targets[0])
                else:
                    keys = option_keys(question)
                    if len(targets) != len(keys):
                        raise Drop("target_length_mismatch")
                    target = distribution(keys, dict(zip(keys, targets, strict=True)))
            except (Drop, TypeError, ValueError) as error:
                stats.dropped_questions[getattr(error, "reason", "bad_target")] += 1
                continue
            key = member["question_id"] or "decision"
            if key in questions:
                n = 2
                while f"{key}~{n}" in questions:
                    n += 1
                key = f"{key}~{n}"
                stats.count("renamed_duplicate_question_id", 1)
            questions[key], expected[key] = question, target
        if not questions:
            stats.dropped["no_labeled_questions"] += 1
            return None
        digest = hashlib.sha1(first["state"].encode()).hexdigest()
        row_id = f"{first['group_id']}#{digest[:10]}"
        if row_id in seen_ids:
            n = 2
            while f"{row_id}~{n}" in seen_ids:
                n += 1
            row_id = f"{row_id}~{n}"
            stats.count("split_noncontiguous_group", 1)
        seen_ids.add(row_id)
        task = first["source"]
        meta: dict[str, Any] = {
            "task": task,
            "variants": sorted({m["variant"] for m in members if m["variant"]}),
            "split": first["split"],
            "license_use": first["license_use"],
        }
        if task.startswith("procedural-typed-decisions/") and bytes.fromhex(digest) in ptd:
            meta["duplicate_of"] = "tasksource/procedural-typed-decisions/all"
            stats.count("flagged_duplicate_of", "procedural-typed-decisions")
        if task.startswith("procedural-typed-decisions/"):
            stats.count("procedural_rows", "all")
        stats.count("task_license", f"{task} :: {first['license']}")
        return {
            "state": parse_state(first["state"]),
            "questions": questions,
            "expected": expected,
            "source": source,
            "license": first["license"] or "unspecified",
            "id": row_id,
            "meta": meta,
        }

    pending: list[dict[str, Any]] = []
    pending_key: tuple[str, str, str] | None = None
    for record in _parquet_batches(fetched.files, JEV_COLUMNS, batch_size=2048):
        stats.input_rows += 1
        use = record["license_use"]
        stats.count("input_license_use", use)
        if use != "commercial":
            stats.count("excluded_tasks_by_license_use", f"{use} :: {record['source']}")
            stats.dropped[f"license_use_{use}"] += 1
            continue
        if record["split"] != "train":
            stats.dropped["not_train_split"] += 1
            continue
        key = (record["group_id"], record["state"], record["source"])
        if key != pending_key and pending:
            if (row := build(pending)) is not None:
                yield row
            pending = []
        pending_key = key
        pending.append(record)
    if pending and (row := build(pending)) is not None:
        yield row


CONVERTERS: dict[str, Converter] = {
    "procedural-typed-decisions": convert_procedural,
    "sn92-generalist-train-v1": convert_generalist,
    "sn92-specialists": convert_specialists,
    "tasksource-jev-typed-decisions": convert_jev,
}


