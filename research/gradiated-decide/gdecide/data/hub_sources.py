"""Convert public typed-decision datasets on the Hugging Face Hub into decision-model training rows.

Run from ``research/gradiated-decide/``::

    python -m gdecide.data.hub_sources --out ../../.agents/runtime/gdecide/data/hub [--sources ...] [--limit N]

Every source is downloaded anonymously at a pinned dataset commit (``/resolve/<sha>/<file>``; LFS files are checked
against their sha256) into ``<out>/_raw/``. Downloaded files are parsed as data only (JSON lines and parquet); nothing
in them is executed. Output is one ``<slug>.jsonl.gz`` per source plus ``manifest.json``. One output line::

    {"state": str | JSON object, "questions": {key: question}, "expected": {key: target},
     "source": "<dataset>/<config-or-subset>", "license": str, "id": str, "meta": {...}}

Questions use the Decisions API / pplx_decider shape (``choice`` with ``criteria`` mapping option key -> description
or null, ``noul`` with optional ``true``/``false`` criteria, ``score`` with a list of level descriptions). Targets:
an option key (hard) or ``{option_key: prob}`` with only nonzero entries, normalised (soft) for ``choice``/``score``
(score keys are level indices ``"0"..``); a float P(true) for ``noul``. Questions without a usable label are dropped;
rows left without questions are dropped. Every written row passes ``validate_row`` (the pplx_decider encoder's
``validate`` rules plus target checks). ``meta`` carries the source task name and provenance fields used to filter
the mix later (e.g. ``generator_model``, ``duplicate_of``); rows are flagged, never silently merged across sources.
"""

