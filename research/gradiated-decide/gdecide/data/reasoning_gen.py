# --------------------------------------------------------------------------------------------- time helpers


@functools.cache
def zone(iana: str) -> ZoneInfo:
    return ZoneInfo(iana)


def aware(iana: str, naive: datetime) -> datetime:
    """The aware datetime for a local wall time; Retry when the wall time is skipped or repeated by a clock change."""
    z = zone(iana)
    a, b = naive.replace(tzinfo=z, fold=0), naive.replace(tzinfo=z, fold=1)
    if a.utcoffset() != b.utcoffset():
        raise Retry("nonexistent_or_ambiguous_local_time")
    return a


def to_utc(iana: str, naive: datetime) -> datetime:
    return aware(iana, naive).astimezone(UTC)


def wall(iana: str, instant: datetime) -> datetime:
    """Local wall time (naive) of a UTC instant; Retry when that wall time is ambiguous."""
    naive = instant.astimezone(zone(iana)).replace(tzinfo=None)
    aware(iana, naive)
    return naive


@functools.cache
def transitions(iana: str, year: int) -> tuple[tuple[datetime, timedelta, timedelta], ...]:
    """(UTC instant, old offset, new offset) of every clock change of a zone in a year (all are on whole UTC hours)."""
    z = zone(iana)
    out = []
    t = datetime(year, 1, 1, tzinfo=UTC)
    end = datetime(year + 1, 1, 1, tzinfo=UTC)
    prev = t.astimezone(z).utcoffset()
    while t < end:
        t += timedelta(hours=1)
        off = t.astimezone(z).utcoffset()
        if off != prev:
            out.append((t, prev, off))
            prev = off
    return tuple(out)


def transitions_between(iana: str, a: datetime, b: datetime) -> list[tuple[datetime, timedelta, timedelta]]:
    return [tr for y in range(a.year - 1, b.year + 1) for tr in transitions(iana, y) if a < tr[0] <= b]


def date_near_dst(rng: random.Random, iana: str, before: int = 9, after: int = 3) -> date:
    year = rng.randint(2025, 2028)
    trs = transitions(iana, year)
    if trs and rng.random() < 0.75:
        local = rng.choice(trs)[0].astimezone(zone(iana)).date()
        return local + timedelta(days=rng.randint(-before, after))
    return date(year, 1, 1) + timedelta(days=rng.randrange(365))


def city_of(iana: str) -> str:
    return next(c for c, z in CITIES.items() if z == iana)


def dst_note(iana: str, tr: tuple[datetime, timedelta, timedelta], style: int) -> str:
    t, old, new = tr
    before = t.astimezone(timezone(old)).replace(tzinfo=None)
    after = t.astimezone(zone(iana)).replace(tzinfo=None)
    city = city_of(iana)
    if new > old:
        return (f"Note: clocks in {city} go forward one hour on {fmt_date(after.date(), style)}; at "
                f"{before:%H:%M} local time they jump to {after:%H:%M}.")
    return (f"Note: clocks in {city} go back one hour on {fmt_date(after.date(), style)}; at {before:%H:%M} local "
            f"time they are set back to {after:%H:%M}.")


def is_bday(d: date, hol: set[date] | frozenset[date]) -> bool:
    return d.weekday() < 5 and d not in hol


def nth_bday_after(d: date, n: int, hol: set[date] | frozenset[date]) -> date:
    while n > 0:
        d += timedelta(days=1)
        if is_bday(d, hol):
            n -= 1
    return d


def last_day(y: int, m: int) -> int:
    return ((date(y + m // 12, m % 12 + 1, 1)) - timedelta(days=1)).day


def add_months(d: date, n: int) -> date:
    """Same day number n months later, or the last day of that month when it has no such day."""
    k = d.year * 12 + d.month - 1 + n
    y, m = divmod(k, 12)
    return date(y, m + 1, min(d.day, last_day(y, m + 1)))


def add_months_overflow(d: date, n: int) -> date:
    """Buggy month arithmetic: a missing day rolls over into the next month (31 Jan + 1 month = 3 Mar)."""
    k = d.year * 12 + d.month - 1 + n
    y, m = divmod(k, 12)
    ld = last_day(y, m + 1)
    return date(y, m + 1, min(d.day, ld)) + timedelta(days=max(0, d.day - ld))


def hm(text: str) -> time:
    h, m = text.split(":")
    return time(int(h), int(m))


# --------------------------------------------------------------------------------------------- formatting


def fmt_date(d: date, style: int) -> str:
    wd, mon = WEEKDAYS[d.weekday()], MONTHS[d.month - 1]
    if style == 0:
        return f"{wd[:3]} {d.day} {mon[:3]} {d.year}"
    if style == 1:
        return d.isoformat()
    if style == 2:
        return f"{wd} {d.day} {mon} {d.year}"
    return f"{wd}, {mon} {d.day}, {d.year}"


def fmt_time(t: time | datetime, style: int) -> str:
    if style == 2:
        h = t.hour % 12 or 12
        return f"{h}:{t.minute:02d} {'am' if t.hour < 12 else 'pm'}"
    return f"{t.hour:02d}:{t.minute:02d}"


def fmt_dt(dt: datetime, style: int) -> str:
    if style == 0:
        return f"{fmt_date(dt.date(), 0)}, {fmt_time(dt, 0)}"
    if style == 1:
        return f"{dt.date().isoformat()} {fmt_time(dt, 1)}"
    if style == 2:
        return f"{fmt_date(dt.date(), 2)} at {fmt_time(dt, 2)}"
    return f"{fmt_time(dt, 3)} on {fmt_date(dt.date(), 3)}"


def dt_key(dt: datetime) -> str:
    return f"{MONTHS[dt.month - 1][:3].lower()}_{dt.day}_{dt.hour:02d}{dt.minute:02d}"


def date_key(d: date) -> str:
    return f"{MONTHS[d.month - 1][:3].lower()}_{d.day}_{d.year}"


def fmt_money(cents: int, cur: str) -> str:
    sign = "-" if cents < 0 else ""
    cents = abs(cents)
    return f"{sign}{CURRENCIES[cur]}{cents // 100:,}.{cents % 100:02d}"


def money_key(cents: int, cur: str) -> str:
    sign = "minus_" if cents < 0 else ""
    cents = abs(cents)
    return f"{cur.lower()}_{sign}{cents // 100}_{cents % 100:02d}"


def round_half_up(value: Fraction, places: int = 0) -> int:
    """value * 10**places rounded half away from zero, as an integer."""
    scaled = value * 10**places
    n = math.floor(abs(scaled) + Fraction(1, 2))
    return n if scaled >= 0 else -n


def dec(value: Fraction, places: int) -> str:
    """Decimal string of value rounded half-up to ``places`` decimals."""
    n = round_half_up(value, places)
    s = str(Decimal(n).scaleb(-places))
    return s


def plain(d: Decimal | str) -> str:
    """Decimal string without exponent and without trailing zeros."""
    d = Decimal(d).normalize()
    s = format(d, "f")
    return s


def frac(text: str) -> Fraction:
    return Fraction(Decimal(text))


