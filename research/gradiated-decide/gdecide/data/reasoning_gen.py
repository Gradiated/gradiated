"""Deterministic generator of code-labelled decision problems that need multi-step date/time and numeric reasoning.

Run from ``research/gradiated-decide/``::

    python -m gdecide.data.reasoning_gen --out DIR --n 60000 --seed 1 [--test-n 3000 --test-seed 999]

Writes ``DIR/reasoning-gen.jsonl.gz`` (train), ``DIR/reasoning-gen-test.jsonl.gz`` (held out: another seed, no state
shared with train) and ``DIR/reasoning-gen-manifest.json``. Rows have the format of ``gdecide.data.hub_sources``
(``state``, ``questions``, ``expected``, ``source``, ``license``, ``id``, ``meta``) and pass its ``validate_row``.

Every label is computed by code from the generated facts; the facts themselves are stored in ``meta["facts"]`` so
that tests can recompute labels independently. Families (``meta["family"]``):

1. ``deadline``: windows that open on the n-th business day after receipt and last N elapsed hours or N business
   days, with listed closure days, DST changes and an explicit inclusive/exclusive closing instant.
2. ``roster``: shifts in one or two offices in different zones; minimum rest, maximum shift length and a weekly cap
   attributed by start time in the home zone, across clock-change nights.
3. ``limits``: card limits with pending pre-authorisations, captures, releases, refunds posting on a later day and
   cash fees; project budgets that exclude VAT and drop withdrawn claims.
4. ``threshold``: measured values with a conservative uncertainty correction, unit conversions and
   pass / narrow fail / clear fail bands with an explicit rule for values exactly at the limit.
5. ``interest``: actual/360 or actual/365 accrual from and including the start to but excluding the end, a rate reset
   on the second business day after fixing and a mid-period principal repayment.
6. ``warranty``: terms of N months from delivery under a month-end rule, extensions by repair days counted
   inclusively and an absolute cap from manufacture.
7. ``judge``: a request with a small multi-step calculation and a worked response that is either correct or has one
   planted error (arithmetic slip, wrong order, unit error, wrong rounding, missed step).
8. ``policy``: clause lists with a later amendment (sometimes effective from a date), an application with distractor
   facts and a summary line that may state a wrong total.

Wrong options of choice questions are the answers of deliberately buggy computations (DST ignored, off-by-one day,
inclusive/exclusive swapped, tax included, correction omitted, ...). Labels are one-hot. noul labels are balanced
50/50 and choice options are shuffled, so the gold position is uniform. Only the Python standard library is used.
"""

