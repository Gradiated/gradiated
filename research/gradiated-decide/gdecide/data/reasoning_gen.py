def filler(rng: random.Random, specific: list[str], target: int) -> str:
    """Irrelevant paragraphs (family-specific distractors first) of roughly ``target`` characters."""
    pool = list(specific) + rng.sample(FILLER, min(len(FILLER), 8))
    rng.shuffle(pool)
    out, n = [], 0
    for s in pool:
        if n >= target:
            break
        out.append(s)
        n += len(s) + 1
    return " ".join(out)


def assemble(rng: random.Random, core: list[str], long: bool, specific: list[str], head: str | None = None) -> str:
    """State text: optional header, core blocks, and for long states distractor paragraphs before and after."""
    blocks = list(core)
    if long:
        before = filler(rng, specific[: len(specific) // 2], rng.randint(250, 700))
        after = filler(rng, specific[len(specific) // 2:], rng.randint(300, 900))
        blocks = ([f"Background: {before}"] if before else []) + blocks + ([f"Other notes: {after}"] if after else [])
    if head:
        blocks.insert(0, head)
    return "\n\n".join(b for b in blocks if b)


