def gen_roster_row(rng: random.Random, long: bool, pseed: int) -> dict[str, Any]:
    plan = random.Random(pseed)  # variant and target label: fixed across retries
    variant = plan.choices(["compliant", "count", "first"], weights=[4, 3, 3])[0]
    if variant == "compliant":
        want = "compliant" if plan.random() < 0.5 else "breach"
    elif variant == "count":
        want = f"count:{plan.randrange(4)}"
    else:
        want = "first:" + plan.choice(["rest", "shift_length", "weekly_cap", "none"])
    trap = plan.random() < 0.4
    for attempt in range(6000):
        try:
            f = gen_roster(rng, long, want, trap and attempt < 4000)
            break
        except Retry:
            continue
    else:
        raise Retry("roster")
    return render_roster(rng, f, long, variant)


