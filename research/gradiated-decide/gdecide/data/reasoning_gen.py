PRODUCTS = ["dishwasher", "e-bike", "laptop", "espresso machine", "heat pump", "washing machine", "camera",
            "standing desk", "solar inverter", "refrigerator", "lawn mower", "television"]


def warranty_ends(f: dict[str, Any], bug: str | None = None) -> tuple[date, date | None]:
    deliv, manuf = date.fromisoformat(f["delivered"]), date.fromisoformat(f["manufactured"])
    addm = add_months_overflow if bug == "month_overflow" else add_months
    term_end = addm(manuf if bug == "term_from_manufacture" else deliv, f["term_months"])
    ext = 0
    if bug != "extensions_ignored":
        for a, b in f["repairs"]:
            ext += (date.fromisoformat(b) - date.fromisoformat(a)).days + (0 if bug == "repair_days_exclusive" else 1)
    cap_end = None if bug == "cap_ignored" else addm(manuf, f["cap_months"])
    return term_end + timedelta(days=ext), cap_end


def warranty_status(f: dict[str, Any], claim: date, bug: str | None = None) -> str:
    ext_end, cap_end = warranty_ends(f, bug)
    last = ext_end if cap_end is None else min(ext_end, cap_end)
    if claim <= last:
        return "covered"
    if cap_end is None or ext_end < cap_end:
        return "expired_term"
    return "expired_cap"


def gen_warranty(rng: random.Random, long: bool, pseed: int) -> dict[str, Any]:
    plan = random.Random(pseed)  # variant and target label: fixed across retries
    style = rng.randrange(4)
    product = rng.choice(PRODUCTS)
    manuf = date(rng.randint(2023, 2026), rng.randint(1, 12), rng.randint(1, 28))
    deliv = manuf + timedelta(days=rng.choice([rng.randint(10, 90), rng.randint(90, 400)]))
    if rng.random() < 0.4:  # month-end deliveries make the month-end rule matter
        ld = last_day(deliv.year, deliv.month)
        deliv = deliv.replace(day=rng.choice([d for d in (29, 30, 31) if d <= ld] or [ld]))
    term = rng.choice([6, 12, 18, 24, 36])
    cap = term + rng.choice([3, 6, 6, 12, 12, 18])
    term_end = add_months(deliv, term)
    repairs = []
    cursor = deliv + timedelta(days=rng.randint(20, 120))
    for _ in range(rng.choice([0, 1, 1, 2, 2, 3])):
        if cursor >= term_end - timedelta(days=30):
            break
        a = cursor
        b = a + timedelta(days=rng.randint(0, 25))
        repairs.append([a.isoformat(), b.isoformat()])
        cursor = b + timedelta(days=rng.randint(15, 120))
    f: dict[str, Any] = {"product": product, "manufactured": manuf.isoformat(), "delivered": deliv.isoformat(),
                         "term_months": term, "cap_months": cap, "repairs": repairs, "claims": []}
    ext_end, cap_end = warranty_ends(f)
    if ext_end == cap_end:
        raise Retry("tie")
    last = min(ext_end, cap_end)
    reason = "expired_term" if ext_end < cap_end else "expired_cap"
    variant = plan.choices(["status", "covered", "last_day", "count"], weights=[3, 3, 2, 2])[0]
    plan_target = plan.choice(["covered", "expired_term", "expired_cap"])
    plan_flag = plan.random()

    def claim_for(target: str) -> date:
        if target == "covered":
            lo = date.fromisoformat(repairs[-1][1]) + timedelta(days=1) if repairs else deliv + timedelta(days=1)
            r = rng.random()
            if r < 0.3:
                c = last
            elif r < 0.75:
                c = last - timedelta(days=rng.randint(1, 12))
            else:
                c = lo + timedelta(days=rng.randint(0, max(0, (last - lo).days)))
            if c < lo or c > last:
                raise Retry("claim_range")
            return c
        if target != reason:
            raise Retry("reason")
        return last + timedelta(days=rng.choice([1, 1, 2, rng.randint(1, 10), rng.randint(10, 90)]))

    questions, expected = {}, {}
    if variant in ("status", "covered"):
        if variant == "status":
            target = plan_target
        else:
            target = "covered" if plan_flag < 0.5 else reason
        claim = claim_for(target)
        assert warranty_status(f, claim) == target
        f["claims"].append({"name": "claim", "date": claim.isoformat()})
        if variant == "status":
            questions["status"] = qchoice(rng, rng.choice([
                f"What is the warranty status of the {product} on the claim date?",
                "How should the claim be decided?",
                "Is the claim within the warranty, and if not, which limit has run out?",
            ]), [("covered", "Covered by the warranty"),
                 ("expired_term", "Not covered: the warranty term (including extensions) has ended"),
                 ("expired_cap", "Not covered: the absolute cap from manufacture has been reached")])
            expected["status"] = target
            label: Any = target
        else:
            questions["covered"] = qnoul(rng.choice([
                "Is the claim covered by the warranty?", f"Is the {product} still under warranty on the claim date?",
            ]), "Yes, it is covered", "No, the cover has ended")
            expected["covered"] = 1.0 if target == "covered" else 0.0
            label = target == "covered"
    elif variant == "last_day":
        gold = (date_key(last), fmt_date(last, style))
        wrong = []
        for bug in ("repair_days_exclusive", "month_overflow", "cap_ignored", "extensions_ignored",
                    "term_from_manufacture"):
            e, c = warranty_ends(f, bug)
            v = e if c is None else min(e, c)
            wrong.append((date_key(v), fmt_date(v, style)))
        extra = [(date_key(last + timedelta(days=d)), fmt_date(last + timedelta(days=d), style)) for d in (1, -1, 30)]
        opts = fill_options(rng, gold, wrong, extra)
        questions["last_day"] = qchoice(rng, rng.choice([
            "What is the last day of warranty cover?", f"Until which date (inclusive) is the {product} covered?",
        ]), opts)
        expected["last_day"] = gold[0]
        label = gold[0]
    else:
        k = plan.randint(2, 4)
        count = plan.randint(0, k)
        targets = ["covered"] * count + [reason] * (k - count)
        rng.shuffle(targets)
        for j, t in enumerate(targets):
            f["claims"].append({"name": f"claim {j + 1}", "date": claim_for(t).isoformat()})
        questions["count_covered"] = qscore(f"How many of the {k} claims are covered by the warranty?",
                                            [f"{i} of {k}" for i in range(k + 1)])
        expected["count_covered"] = str(count)
        label = count
    rules = [
        f"The warranty lasts {term} months from delivery. It ends at the end of the day with the same day number "
        f"{term} months after delivery; if that month has no such day, it ends at the end of that month's last day.",
        "Each repair extends the warranty by the number of days the product was in the workshop, counting both the "
        "drop-off day and the collection day.",
        f"Absolute cap: whatever the extensions, there is no cover after {cap} months from the date of manufacture "
        f"(same month-end rule; cover runs to the end of that day).",
        "A claim is covered if it is made on or before the last day of cover.",
    ]
    facts = [f"Manufactured: {fmt_date(manuf, style)}.", f"Delivered to the customer: {fmt_date(deliv, style)}."]
    for i, (a, b) in enumerate(repairs):
        facts.append(f"Repair {i + 1}: dropped off {fmt_date(date.fromisoformat(a), style)}, collected "
                     f"{fmt_date(date.fromisoformat(b), style)}.")
    for c in f["claims"]:
        facts.append(f"{c['name'].capitalize()} made on {fmt_date(date.fromisoformat(c['date']), style)}.")
    head = rng.choice([f"Warranty claim for a {product}.", f"{rng.choice(FIRMS)} warranty desk: {product}.",
                       f"Customer {rng.choice(PEOPLE)} asks about warranty on a {product}."])
    specific = [
        f"The {product} was bought online and shipped from a warehouse {rng.randint(50, 900)} km away.",
        f"The invoice is dated {fmt_date(deliv - timedelta(days=rng.randint(1, 10)), style)}; the warranty runs "
        f"from delivery, not from the invoice.",
        "Accessories carry a separate warranty that is not relevant here.",
        f"The customer registered the product online {rng.randint(2, 40)} days after delivery.",
        "Statutory consumer rights are not affected and are assessed separately.",
    ] + ([f"A courtesy call was made by {rng.choice(PEOPLE)} after the last repair."] if repairs else [
        "The customer has not needed any repair so far."])
    state = assemble(rng, ["Warranty rules:\n" + "\n".join("- " + r for r in rules), "Facts:\n" + "\n".join(facts)],
                     long, specific, head)
    return {"family": "warranty", "variant": variant, "state": state, "questions": questions, "expected": expected, "facts": f,
                "label": label}


