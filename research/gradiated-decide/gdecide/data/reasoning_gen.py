def card_sim(f: dict[str, Any], bugs: frozenset[str] = frozenset()) -> dict[str, Any]:
    avail = f["limit"] - f["balance"]
    fee_pct, fee_min = frac(f["cash_fee_pct"]), f["cash_fee_min"]
    timeline = []
    for idx, e in enumerate(f["events"]):
        timeline.append((e["date"], e["time"], 1, idx, e))
        if e["kind"] == "refund" and "refund_ignored" not in bugs:
            when = (e["date"], e["time"]) if "refund_on_announce" in bugs else (e["posts"], "00:00")
            timeline.append((when[0], when[1], 0, idx, {"kind": "refund_post", "amount": e["amount"]}))
    timeline.sort(key=lambda t: (t[0], t[1], t[2], t[3]))
    holds: dict[str, int] = {}
    approved: dict[str, bool] = {}
    declined: list[str] = []
    alert = None
    for d, _, _, _, e in timeline:
        kind = e["kind"]
        if kind in ("purchase", "hold", "cash"):
            need = e["amount"]
            if kind == "cash" and "fees_ignored" not in bugs:
                need += max(fee_min, round_half_up(Fraction(e["amount"]) * fee_pct / 100))
            ok = need <= avail
            approved[e["id"]] = ok
            if not ok:
                declined.append(e["id"])
                continue
            if kind == "hold" and "holds_ignored" in bugs:
                holds[e["id"]] = 0
                continue
            avail -= need
            if kind == "hold":
                holds[e["id"]] = need
        elif kind == "capture":
            if approved.get(e["ref"]) and "release_ignored" not in bugs:
                avail += holds.pop(e["ref"], 0)
            avail -= e["amount"]
        elif kind == "release":
            if approved.get(e["ref"]) and "release_ignored" not in bugs:
                avail += holds.pop(e["ref"], 0)
        elif kind == "refund_post":
            avail += e["amount"]
        if alert is None and avail < f["alert_below"]:
            alert = d  # available credit starts above the alert level, so this is the first fall below it
    return {"declined": declined, "first": declined[0] if declined else None, "alert": alert, "final": avail,
            "approved": approved}


