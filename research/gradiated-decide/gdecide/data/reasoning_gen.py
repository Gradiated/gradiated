def qnoul(instructions: str, true: str, false: str) -> dict[str, Any]:
    q = clean_question("noul", instructions, {"true": true, "false": false})
    assert check_question(q) is None
    return q


def qchoice(rng: random.Random, instructions: str, options: list[tuple[str, str]]) -> dict[str, Any]:
    keys = [k for k, _ in options]
    assert len(set(keys)) == len(keys) and len(keys) >= 2, keys
    items = list(options)
    rng.shuffle(items)
    q = clean_question("choice", instructions, dict(items))
    assert check_question(q) is None
    return q


def qscore(instructions: str, levels: list[str]) -> dict[str, Any]:
    q = clean_question("score", instructions, levels)
    assert check_question(q) is None
    return q


def bands(rng: random.Random, value: int, step: int, n_levels: int, fmt, floor_at: int | None = 0):
    """Ordered band descriptions and the gold level index for ``value`` (bands [e_j, e_{j+1}), e in steps)."""
    for _ in range(20):
        g = rng.randrange(n_levels)
        base = (value // step) * step
        edges = [base + (k - g + 1) * step for k in range(n_levels - 1)]
        if floor_at is not None and edges[0] <= floor_at:
            continue
        levels = [f"Less than {fmt(edges[0])}"]
        levels += [f"{fmt(edges[k])} to under {fmt(edges[k + 1])}" for k in range(n_levels - 2)]
        levels.append(f"{fmt(edges[-1])} or more")
        return levels, g, edges
    raise Retry("bands")


def fill_options(rng: random.Random, gold: tuple[str, str], wrong: list[tuple[str, str]], extra: list[tuple[str, str]],
                 lo: int = 4, hi: int = 5) -> list[tuple[str, str]]:
    """Gold plus distinct wrong options (buggy answers first, then extras), between lo and hi options."""
    seen = {gold[0]}
    out = [gold]
    for k, v in wrong:
        if k not in seen and len(out) < hi:
            seen.add(k)
            out.append((k, v))
    rng.shuffle(extra)
    for k, v in extra:
        if len(out) >= lo:
            break
        if k not in seen:
            seen.add(k)
            out.append((k, v))
    if len(out) < min(lo, 3):
        raise Retry("too_few_options")
    return out


