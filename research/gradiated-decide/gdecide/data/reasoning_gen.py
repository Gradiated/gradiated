def interest_amount(f: dict[str, Any], bug: str | None = None) -> int:
    hol = frozenset(date.fromisoformat(h) for h in f["holidays"])
    start, end = date.fromisoformat(f["start"]), date.fromisoformat(f["end"])
    basis = f["basis"]
    if bug == "basis_swapped":
        basis = 365 if basis == 360 else 360
    if bug == "end_inclusive":
        end += timedelta(days=1)
    reset = None
    if f["fixing"]:
        fixing = date.fromisoformat(f["fixing"])
        reset = {"reset_at_fixing": fixing, "reset_one_day": nth_bday_after(fixing, 1, hol)}.get(
            bug, nth_bday_after(fixing, 2, hol))
        if bug == "rate_change_ignored":
            reset = None
    rep = f["repayment"]
    rep_date = None
    if rep and bug != "repayment_ignored":
        rep_date = date.fromisoformat(rep["date"]) + (timedelta(days=1) if bug == "repayment_next_day" else timedelta())
    total = Fraction(0)
    r1, r2 = frac(f["rate1"]), frac(f["rate2"]) if f["fixing"] else None
    d = start
    while d < end:
        rate = r2 if reset is not None and d >= reset else r1
        principal = f["principal"] - (rep["amount"] if rep_date and d >= rep_date else 0)
        total += Fraction(principal) * rate / 100 / basis
        d += timedelta(days=1)
    return round_half_up(total)


INTEREST_BUGS = ["basis_swapped", "end_inclusive", "rate_change_ignored", "reset_at_fixing", "reset_one_day",
                 "repayment_ignored", "repayment_next_day"]


def gen_interest(rng: random.Random, long: bool, pseed: int) -> dict[str, Any]:
    plan = random.Random(pseed)  # variant and target label: fixed across retries
    cur = rng.choice(["USD", "EUR", "GBP", "AUD", "CHF"])
    style = rng.randrange(4)
    start = date(rng.randint(2025, 2028), rng.randint(1, 12), rng.randint(1, 28))
    days = rng.randint(31, 184)
    end = start + timedelta(days=days)
    principal = rng.choice([50, 75, 100, 120, 150, 200, 250, 400, 500, 750, 1000]) * 1000 * 100
    rate1 = plain(Decimal(rng.randint(200, 800) * 125) / 10000)
    has_reset = rng.random() < 0.8
    fixing = rate2 = None
    hol: list[date] = []
    if has_reset:
        lo, hi = start + timedelta(days=5), end - timedelta(days=12)
        if hi <= lo:
            raise Retry("short")
        fixing_d = lo + timedelta(days=rng.randint(0, (hi - lo).days))
        if rng.random() < 0.5:  # prefer Thursdays/Fridays so that the reset crosses a weekend
            fixing_d += timedelta(days=(rng.choice([3, 4]) - fixing_d.weekday()) % 7)
        if fixing_d.weekday() >= 5 or fixing_d >= hi:
            raise Retry("fixing")
        fixing = fixing_d.isoformat()
        if rng.random() < 0.3:
            h = nth_bday_after(fixing_d, rng.randint(1, 2), frozenset())
            hol = [h]
        rate2 = plain(Decimal(rate1) + Decimal(rng.choice([-1, 1]) * rng.randint(1, 12) * 125) / 1000)
        if Decimal(rate2) <= 0:
            raise Retry("rate")
    repayment = None
    if rng.random() < 0.55:
        rd = start + timedelta(days=rng.randint(3, days - 3))
        repayment = {"date": rd.isoformat(), "amount": principal * rng.choice([10, 20, 25, 30, 40, 50]) // 100}
    f = {"currency": cur, "principal": principal, "start": start.isoformat(), "end": end.isoformat(),
         "basis": rng.choice([360, 365]), "rate1": rate1, "fixing": fixing, "rate2": rate2,
         "holidays": [h.isoformat() for h in hol], "repayment": repayment}
    gold = interest_amount(f)
    wrongs = []
    for bug in INTEREST_BUGS:
        if (bug.startswith("reset") or bug == "rate_change_ignored") and not fixing:
            continue
        if bug.startswith("repayment") and not repayment:
            continue
        v = interest_amount(f, bug)
        if v != gold:
            wrongs.append((bug, v))
    variant = plan.choices(["amount", "check", "band"], weights=[4, 3, 2])[0]
    questions, expected = {}, {}
    if variant == "amount":
        rng.shuffle(wrongs)
        wrong_opts = [(money_key(v, cur), fmt_money(v, cur)) for _, v in wrongs]
        extra = [(money_key(gold + d, cur), fmt_money(gold + d, cur)) for d in (100, -100, gold // 10)]
        opts = fill_options(rng, (money_key(gold, cur), fmt_money(gold, cur)), wrong_opts, extra, lo=4, hi=5)
        questions["interest"] = qchoice(rng, rng.choice([
            "How much interest is due for the period, rounded to the cent?",
            "What is the interest payable at the end of the period?",
            "Compute the interest due on the end date.",
        ]), opts)
        expected["interest"] = money_key(gold, cur)
        label: Any = gold
    elif variant == "check":
        correct = plan.random() < 0.5
        if not correct and not wrongs:
            raise Retry("no_wrong")
        shown = gold if correct else rng.choice(wrongs)[1]
        f["stated"] = shown
        questions["statement_correct"] = qnoul(rng.choice([
            f"The lender's notice states interest of {fmt_money(shown, cur)} for the period. Is that correct?",
            f"Is {fmt_money(shown, cur)} the correct interest for the period under the terms above?",
        ]), "Yes, the stated amount is correct", "No, the correct amount is different")
        expected["statement_correct"] = 1.0 if correct else 0.0
        label = correct
    else:
        step = max(100, (gold // 6) // 1000 * 1000) or 1000
        levels, g, _ = bands(rng, gold, step, 4, lambda c: fmt_money(c, cur))
        questions["interest_band"] = qscore("In which range does the interest due for the period fall?", levels)
        expected["interest_band"] = str(g)
        label = gold
    basis_text = {360: "actual/360 (actual days elapsed divided by 360)",
                  365: "actual/365 (actual days elapsed divided by 365)"}[f["basis"]]
    terms = [
        f"Principal: {fmt_money(principal, cur)}, drawn on {fmt_date(start, style)}; interest is paid with the "
        f"principal on {fmt_date(end, style)}.",
        f"Day count: {basis_text}. Interest accrues for each day from and including {fmt_date(start, style)} to but "
        f"excluding {fmt_date(end, style)}, on the principal outstanding that day, at the rate applying that day.",
        f"Initial rate: {rate1}% per annum.",
    ]
    if fixing:
        terms.append(f"The rate was refixed on {fmt_date(date.fromisoformat(fixing), style)} at {rate2}% per annum. "
                     f"A new rate applies from its reset date, the second business day after the fixing date "
                     f"(business days are Monday to Friday"
                     + (f", except the bank holiday on {fmt_date(hol[0], style)}" if hol else "") + ").")
    if repayment:
        terms.append(f"A principal repayment of {fmt_money(repayment['amount'], cur)} was made on "
                     f"{fmt_date(date.fromisoformat(repayment['date']), style)}; the outstanding principal is reduced "
                     f"from that day (interest for that day is on the reduced principal).")
    terms.append("Interest is computed exactly and rounded to the cent (half up) only at the end.")
    head = rng.choice([
        f"Loan terms between {rng.choice(FIRMS)} and its bank.",
        f"Term deposit / loan interest calculation ({cur}).",
        f"Bridge loan to {rng.choice(FIRMS)}: interest terms.",
    ])
    specific = [
        f"The facility agreement was signed by {rng.choice(PEOPLE)}.",
        f"An arrangement fee of {fmt_money(principal // 200, cur)} was paid upfront and is not interest.",
        f"The bank's published reference rate on {fmt_date(start - timedelta(days=rng.randint(10, 60)), style)} "
        f"was {plain(Decimal(rng.randint(150, 600)) / 100)}%; it is not used in this calculation.",
        "Withholding tax, if any, is handled separately.",
        "Late-payment interest would apply only if the end-date payment were missed.",
    ]
    state = assemble(rng, ["Terms:\n" + "\n".join("- " + t for t in terms)], long, specific, head)
    return {"family": "interest", "variant": variant, "state": state, "questions": questions, "expected": expected, "facts": f,
                "label": label}


