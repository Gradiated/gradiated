def budget_sim(f: dict[str, Any], bugs: frozenset[str] = frozenset()) -> dict[str, Any]:
    rates = {"standard": frac(f["vat_standard"]), "reduced": frac(f["vat_reduced"]), "exempt": Fraction(0)}
    days = sorted({it["date"] for it in f["items"]} | {it["withdrawn"] for it in f["items"] if it["withdrawn"]})
    threshold = Fraction(f["budget_net"]) * frac(f["alert_pct"]) / 100

    def net(it):
        if "vat_included" in bugs:
            return it["gross"]
        rate = rates["standard"] if ("reduced_as_standard" in bugs and it["rate"] == "reduced") else rates[it["rate"]]
        return round_half_up(Fraction(it["gross"]) * 100 / (100 + rate))

    alert, total = None, 0
    for d in days:
        total = sum(net(it) for it in f["items"] if it["date"] <= d and not (
            it["withdrawn"] and it["withdrawn"] <= d and "withdrawn_ignored" not in bugs))
        if alert is None and total >= threshold:
            alert = d
    return {"alert": alert, "final": total, "over": total > f["budget_net"]}


