def policy_eval(f: dict[str, Any]) -> list[str]:
    """Names of the conditions the application fails, in clause order."""
    app = date.fromisoformat(f["application_date"])
    th = dict(f["thresholds"])
    am = f["amendment"]
    if am and (am["effective"] is None or app >= date.fromisoformat(am["effective"])):
        th[am["condition"]] = am["value"]
    fails = []
    if f["domain"] == "relocation":
        hire, start = date.fromisoformat(f["hire_date"]), date.fromisoformat(f["start_date"])
        if app < add_months(hire, th["tenure"]):
            fails.append("tenure")
        km = frac(f["distance"]) * (Fraction(1609344, 1000000) if f["distance_unit"] == "miles" else 1)
        if km < th["distance"]:
            fails.append("distance")
        if (app - start).days > th["timing"] or app < start:
            fails.append("timing")
        if sum(v for _, v in f["income_items"]) > th["income"]:
            fails.append("income")
    else:
        fte = f["full_time"] + Fraction(f["part_time"], 2)
        if fte > th["size"]:
            fails.append("size")
        inst = date.fromisoformat(f["install_date"])
        if (app - inst).days > th["timing"] or app < inst:
            fails.append("timing")
        net = sum(Fraction(g) * 100 / (100 + frac(f["vat_pct"])) for _, g in f["equipment"])
        if net < th["cost"]:
            fails.append("cost")
        if sum(v for _, v in f["turnover"]) > th["turnover"]:
            fails.append("turnover")
    return fails


