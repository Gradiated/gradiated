def judge_solve(t: str, p: dict[str, Any], err: str | None = None) -> tuple[list[str], str]:
    """Worked steps and final answer for a template; ``err`` plants one error (None = correct)."""
    steps: list[str] = []
    if t == "shopping":
        lines = [(name, q, c) for name, q, c in p["items"]]
        totals = [q * c for _, q, c in lines]
        if err == "arithmetic_slip":
            j = p["slip_index"]
            totals[j] += p["slip"]
        sub = sum(totals)
        for (name, q, c), tot in zip(lines, totals):
            steps.append(f"{name}: {q} x {fmt_money(c, 'USD')} = {fmt_money(tot, 'USD')}")
        steps.append(f"Subtotal: {fmt_money(sub, 'USD')}")
        disc_pct, tax_pct = frac(p["discount_pct"]), frac(p["tax_pct"])
        if err == "wrong_order":
            tax = round_half_up(Fraction(sub) * tax_pct / 100)
            steps.append(f"Sales tax {p['tax_pct']}% of {fmt_money(sub, 'USD')} = {fmt_money(tax, 'USD')}")
            disc = round_half_up(Fraction(sub) * disc_pct / 100)
            steps.append(f"Discount {p['discount_pct']}% = {fmt_money(disc, 'USD')}")
            after = sub - disc
            steps.append(f"After discount: {fmt_money(after, 'USD')}")
        else:
            disc = round_half_up(Fraction(sub) * disc_pct / 100)
            after = sub - disc
            steps.append(f"Discount {p['discount_pct']}% of {fmt_money(sub, 'USD')} = {fmt_money(disc, 'USD')}, "
                         f"leaving {fmt_money(after, 'USD')}")
            if err == "unit_error":
                tax = round_half_up(Fraction(after) * tax_pct / 1000)
            elif err == "rounding":
                tax = math.floor(Fraction(after) * tax_pct / 100)
            else:
                tax = round_half_up(Fraction(after) * tax_pct / 100)
            steps.append(f"Sales tax {p['tax_pct']}% of {fmt_money(after, 'USD')} = {fmt_money(tax, 'USD')}")
        ship = 0 if err == "missed_step" else p["shipping"]
        total = after + tax + ship
        if ship:
            steps.append(f"Shipping: {fmt_money(ship, 'USD')}")
        steps.append(f"Total: {fmt_money(after, 'USD')} + {fmt_money(tax, 'USD')}"
                     + (f" + {fmt_money(ship, 'USD')}" if ship else "") + f" = {fmt_money(total, 'USD')}")
        return steps, fmt_money(total, "USD")
    if t == "travel":
        dep = hm(p["depart"])
        legs = p["legs"]
        minutes = 0
        for j, (km, kmh) in enumerate(legs):
            m = Fraction(km * 60, kmh)
            if err == "unit_error" and j == p["slip_index"]:
                hours = Fraction(km, kmh)
                if (hours * 100).denominator != 1 or hours.denominator == 1:
                    raise Retry("unit_error_needs_two_decimal_hours")
                whole = int(hours)
                m = whole * 60 + round_half_up((hours - whole) * 100)
                steps.append(f"Leg {j + 1}: {km} km / {kmh} km/h = {plain(Decimal(km) / Decimal(kmh))} h = "
                             f"{whole} h {int(m - whole * 60)} min")
            else:
                if err == "arithmetic_slip" and j == p["slip_index"]:
                    m += p["slip"]
                steps.append(f"Leg {j + 1}: {km} km at {kmh} km/h takes {int(m)} min")
            minutes += int(m)
        if err != "missed_step":
            minutes += p["break_min"]
            steps.append(f"Break: {p['break_min']} min")
        steps.append(f"Total travel time: {minutes // 60} h {minutes % 60:02d} min")
        arr = datetime.combine(date(2026, 1, 5), dep) + timedelta(minutes=minutes)
        steps.append(f"Arrival: {dep.hour:02d}:{dep.minute:02d} + {minutes // 60} h {minutes % 60:02d} min = "
                     f"{arr:%H:%M}")
        return steps, f"{arr:%H:%M}"
    if t == "payroll":
        hours = [frac(h) for h in p["hours"]]
        total_h = sum(hours)
        if err == "arithmetic_slip":
            total_h += frac(p["slip_hours"])
        steps.append(f"Hours: {' + '.join(p['hours'])} = {plain(Decimal(total_h.numerator) / Decimal(total_h.denominator))} h")
        rate = p["rate"]
        regular = min(total_h, 40)
        over = max(Fraction(0), total_h - 40)
        if err == "wrong_order":  # overtime premium applied to every hour
            gross = total_h * rate * frac(p["ot_mult"])
            steps.append(f"Gross: {plain(Decimal(total_h.numerator) / Decimal(total_h.denominator))} h x "
                         f"{fmt_money(rate, 'USD')} x {p['ot_mult']} = {fmt_money(round_half_up(gross), 'USD')}")
        elif err == "missed_step":  # overtime premium forgotten
            gross = total_h * rate
            steps.append(f"Gross: {plain(Decimal(total_h.numerator) / Decimal(total_h.denominator))} h x "
                         f"{fmt_money(rate, 'USD')} = {fmt_money(round_half_up(gross), 'USD')}")
        else:
            gross = regular * rate + over * rate * frac(p["ot_mult"])
            steps.append(f"Regular: {plain(Decimal(regular.numerator) / Decimal(regular.denominator))} h x "
                         f"{fmt_money(rate, 'USD')}; overtime: "
                         f"{plain(Decimal(over.numerator) / Decimal(over.denominator))} h x {p['ot_mult']} x "
                         f"{fmt_money(rate, 'USD')}; gross {fmt_money(round_half_up(gross), 'USD')}")
        gross_c = round_half_up(gross)
        if err == "unit_error":
            ded = round_half_up(Fraction(gross_c) * frac(p["deduction_pct"]) / 1000)
        else:
            ded = round_half_up(Fraction(gross_c) * frac(p["deduction_pct"]) / 100)
        steps.append(f"Deduction {p['deduction_pct']}%: {fmt_money(ded, 'USD')}")
        net = gross_c - ded
        if err == "rounding":
            net = round_half_up(Fraction(net, 100)) * 100
            final = f"${net // 100:,}"
        else:
            final = fmt_money(net, "USD")
        steps.append(f"Net pay: {final}")
        return steps, final
    if t == "recipe":
        g = frac(p["grams"])
        n = p["portions"]
        w = frac(p["waste_pct"])
        base = g * n
        if err == "arithmetic_slip":
            base += p["slip"]
        steps.append(f"{p['grams']} g x {n} portions = {plain(Decimal(base.numerator) / Decimal(base.denominator))} g")
        total = base if err == "missed_step" else base * (1 + w / 100)
        if err != "missed_step":
            steps.append(f"Add {p['waste_pct']}% for trimming: "
                         f"{dec(total, 2)} g")
        kg = total / (100 if err == "unit_error" else 1000)
        places = 1 if err == "rounding" else 2
        final = f"{dec(kg, places)} kg"
        steps.append(f"In kilograms: {final}")
        return steps, final
    if t == "pct_change":
        a, b = frac(p["old"]), frac(p["new"])
        if err == "arithmetic_slip":
            diff = b - a + frac(p["slip"])
        else:
            diff = b - a
        steps.append(f"Change: {p['new']} - {p['old']} = {plain(Decimal(diff.numerator) / Decimal(diff.denominator))}")
        base = b if err == "wrong_order" else a
        pct = diff / base * 100
        places = 0 if err == "rounding" else 1
        val = dec(pct, places)
        steps.append(f"Relative to {p['new'] if err == 'wrong_order' else p['old']}: "
                     f"{plain(Decimal(diff.numerator) / Decimal(diff.denominator))} / "
                     f"{p['new'] if err == 'wrong_order' else p['old']} x 100 = {val}%")
        final = f"{val}%"
        return steps, final
    raise ValueError(t)


