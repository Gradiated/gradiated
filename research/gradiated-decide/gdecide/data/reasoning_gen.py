def row_rng(seed: int, split: str, i: int, attempt: int) -> random.Random:
    return random.Random(hashlib.sha256(f"{PREFIX}:{seed}:{split}:{i}:{attempt}".encode()).digest())


def make_row(seed: int, split: str, i: int) -> dict[str, Any]:
    family = FAMILIES[i % len(FAMILIES)]
    plan = row_rng(seed, split, i, -1)
    long = plan.random() < 0.5
    pseed = plan.getrandbits(64)
    for attempt in range(400):
        rng = row_rng(seed, split, i, attempt)
        try:
            out = GENERATORS[family](rng, long, pseed)
        except Retry:
            continue
        q = next(iter(out["questions"].values()))
        row = {
            "state": out["state"],
            "questions": out["questions"],
            "expected": out["expected"],
            "source": f"gdecide-gen/reasoning/{family}",
            "license": LICENSE,
            "id": f"reasoning-gen:{split}:{seed}:{i:06d}",
            "meta": {"task": f"reasoning-gen/{family}/{out['variant']}", "family": family, "variant": out["variant"],
                     "qtype": q["type"], "long": long, "generator": VERSION, "label": out["label"],
                     "facts": out["facts"]},
        }
        reason = validate_row(row)
        if reason:
            raise AssertionError(f"{row['id']}: {reason}")
        return row
    raise RuntimeError(f"could not generate row {i} ({family})")


def state_hash(row: dict[str, Any]) -> str:
    state = row["state"] if isinstance(row["state"], str) else json.dumps(row["state"], sort_keys=True)
    return hashlib.sha256(state.encode()).hexdigest()


def generate(n: int, seed: int, split: str, exclude: set[str] | None = None) -> list[dict[str, Any]]:
    """n rows; rows whose state is already used (in this split or in ``exclude``) are replaced by new indices."""
    seen = set(exclude or ())
    rows: list[dict[str, Any]] = []
    i = 0
    while len(rows) < n:
        row = make_row(seed, split, i)
        i += 1
        h = state_hash(row)
        if h in seen:
            continue
        seen.add(h)
        rows.append(row)
    return rows


def summary(rows: list[dict[str, Any]]) -> dict[str, Any]:
    fam, typ, fam_typ, var = Counter(), Counter(), Counter(), Counter()
    noul = defaultdict(Counter)
    lengths = []
    long_n = 0
    for r in rows:
        m = r["meta"]
        fam[m["family"]] += 1
        typ[m["qtype"]] += 1
        fam_typ[f"{m['family']}:{m['qtype']}"] += 1
        var[m["task"]] += 1
        long_n += m["long"]
        lengths.append(len(r["state"]))
        for k, q in r["questions"].items():
            if q["type"] == "noul":
                noul[m["family"]]["true" if r["expected"][k] >= 0.5 else "false"] += 1
    lengths.sort()

    def pct(p):
        return lengths[min(len(lengths) - 1, int(p / 100 * len(lengths)))] if lengths else 0

    return {"rows": len(rows), "families": dict(sorted(fam.items())), "question_types": dict(sorted(typ.items())),
            "family_types": dict(sorted(fam_typ.items())), "tasks": dict(sorted(var.items())),
            "noul_labels": {k: dict(v) for k, v in sorted(noul.items())}, "long_states": long_n,
            "state_chars": {"p10": pct(10), "p50": pct(50), "p90": pct(90), "max": lengths[-1] if lengths else 0}}


def write(rows: list[dict[str, Any]], path: Path) -> str:
    part = path.with_name(path.name + ".part")
    with gzip.GzipFile(part, "wb", compresslevel=6, mtime=0) as raw:
        for r in rows:
            raw.write((json.dumps(r, ensure_ascii=False, separators=(",", ":")) + "\n").encode())
    part.rename(path)
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--n", type=int, default=60000)
    parser.add_argument("--seed", type=int, default=1)
    parser.add_argument("--test-n", type=int, default=3000)
    parser.add_argument("--test-seed", type=int, default=999)
    args = parser.parse_args(argv)
    if args.test_n and args.test_seed == args.seed:
        parser.error("--test-seed must differ from --seed")
    args.out.mkdir(parents=True, exist_ok=True)
    started = _time.time()
    train = generate(args.n, args.seed, "train")
    print(f"train: {len(train)} rows ({_time.time() - started:.0f}s)", file=sys.stderr)
    manifest: dict[str, Any] = {
        "generator": "research/gradiated-decide/gdecide/data/reasoning_gen.py", "version": VERSION,
        "license": LICENSE, "license_note": LICENSE_NOTE, "args": {k: str(v) for k, v in vars(args).items()},
        "train": {"output": "reasoning-gen.jsonl.gz", "seed": args.seed, **summary(train)},
    }
    manifest["train"]["output_sha256"] = write(train, args.out / "reasoning-gen.jsonl.gz")
    if args.test_n:
        test = generate(args.test_n, args.test_seed, "test", exclude={state_hash(r) for r in train})
        manifest["test"] = {"output": "reasoning-gen-test.jsonl.gz", "seed": args.test_seed, **summary(test)}
        manifest["test"]["output_sha256"] = write(test, args.out / "reasoning-gen-test.jsonl.gz")
        print(f"test: {len(test)} rows", file=sys.stderr)
    manifest["seconds"] = round(_time.time() - started, 1)
    (args.out / "reasoning-gen-manifest.json").write_text(json.dumps(manifest, indent=1, ensure_ascii=False) + "\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
