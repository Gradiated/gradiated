def judge_params(rng: random.Random, t: str) -> dict[str, Any]:
    if t == "shopping":
        items = [[name, rng.randint(1, 6), rng.randint(199, 4999)] for name in rng.sample(SHOP_ITEMS, rng.randint(2, 4))]
        return {"items": items, "discount_pct": rng.choice(["5", "10", "12", "15", "20", "25"]),
                "tax_pct": rng.choice(["6", "6.25", "7", "7.5", "8", "8.875", "9.5"]),
                "shipping": rng.choice([0, 499, 599, 750, 999]) or 499,
                "slip_index": rng.randrange(len(items)), "slip": rng.choice([-100, 100, 10, -10, 900, 1000])}
    if t == "travel":
        legs = []
        for _ in range(rng.randint(1, 2)):
            kmh = rng.choice([40, 48, 50, 60, 72, 75, 80, 90, 96, 100, 120])
            minutes = rng.randint(25, 200)
            # distance with whole minutes and a non-round hour fraction
            km = kmh * minutes // 60
            if km * 60 % kmh:
                continue
            legs.append([km, kmh])
        if not legs:
            raise Retry("legs")
        return {"depart": f"{rng.randint(5, 12):02d}:{rng.choice([0, 5, 10, 15, 20, 30, 40, 45, 50]):02d}",
                "legs": legs, "break_min": rng.choice([10, 15, 20, 25, 30, 45]), "slip_index": rng.randrange(len(legs)),
                "slip": rng.choice([-10, 10, 20, -20, 30])}
    if t == "payroll":
        hours = [plain(Decimal(rng.randint(24, 46)) / 4) for _ in range(rng.randint(4, 6))]
        return {"hours": hours, "rate": rng.randint(1500, 4200), "ot_mult": rng.choice(["1.5", "1.25", "2"]),
                "deduction_pct": rng.choice(["12", "15", "18", "20", "22.5"]),
                "slip_hours": rng.choice(["1", "-1", "0.5", "-0.5", "2"])}
    if t == "recipe":
        return {"ingredient": rng.choice(INGREDIENTS), "grams": str(rng.choice([45, 60, 75, 80, 90, 110, 125, 140, 180])),
                "portions": rng.randint(12, 240), "waste_pct": rng.choice(["5", "8", "10", "12", "15"]),
                "slip": rng.choice([100, -100, 1000, 50])}
    if t == "pct_change":
        old = rng.randint(120, 9000)
        new = old + rng.choice([-1, 1]) * rng.randint(5, old // 2)
        return {"old": str(old), "new": str(new), "slip": rng.choice(["10", "-10", "100", "1"]),
                "what": rng.choice(["monthly visitors", "units sold", "support tickets", "average order value (in "
                                    "cents)", "subscribers"])}
    raise ValueError(t)


def judge_request(t: str, p: dict[str, Any]) -> str:
    if t == "shopping":
        items = "; ".join(f"{q} {name} at {fmt_money(c, 'USD')} each" for name, q, c in p["items"])
        return (f"I'm ordering {items}. There is a {p['discount_pct']}% discount on the whole subtotal, then "
                f"{p['tax_pct']}% sales tax on the discounted amount, then a flat shipping charge of "
                f"{fmt_money(p['shipping'], 'USD')} (not taxed). Round the discount and the tax to the nearest cent. "
                f"What is the total I pay?")
    if t == "travel":
        legs = " and then ".join(f"{km} km at an average of {kmh} km/h" for km, kmh in p["legs"])
        return (f"I leave at {p['depart']} and drive {legs}, with one {p['break_min']}-minute break. At what time "
                f"(24-hour clock) do I arrive?")
    if t == "payroll":
        return (f"An employee worked {', '.join(p['hours'])} hours on the days of one week. The rate is "
                f"{fmt_money(p['rate'], 'USD')} per hour; hours above 40 in the week are paid at {p['ot_mult']} "
                f"times the rate. Gross pay is rounded to the cent, then {p['deduction_pct']}% is deducted "
                f"(deduction rounded to the cent). What is the net pay, to the cent?")
    if t == "recipe":
        return (f"A kitchen needs {p['grams']} g of {p['ingredient']} per portion for {p['portions']} portions, plus "
                f"{p['waste_pct']}% extra for trimming and waste. How many kilograms should be ordered? Give the "
                f"answer in kg to 2 decimal places.")
    return (f"Our {p['what']} went from {p['old']} last month to {p['new']} this month. What is the percentage "
            f"change relative to last month, rounded to one decimal place (negative for a decrease)?")


def gen_judge(rng: random.Random, long: bool, pseed: int) -> dict[str, Any]:
    plan = random.Random(pseed)  # variant and target label: fixed across retries
    t = plan.choice(list(JUDGE_ERRORS))
    variant = "verify" if plan.random() < 0.8 else "pick"
    plan_correct = plan.random() < 0.5
    plan_k = plan.randint(2, 3)
    plan_pos = plan.randrange(plan_k)
    p = judge_params(rng, t)
    _gold_steps, gold_final = judge_solve(t, p)

    def response(err: str | None) -> tuple[str, str]:
        steps, final = judge_solve(t, p, err)
        if err and final == gold_final:
            raise Retry("error_invisible")
        if err == "rounding" and t in ("recipe", "pct_change", "payroll"):
            try:
                if Decimal(final.split()[0].rstrip("%").replace("$", "").replace(",", "")) == Decimal(
                        gold_final.split()[0].rstrip("%").replace("$", "").replace(",", "")):
                    raise Retry("rounding_equal")
            except ArithmeticError:
                pass
        form = rng.randrange(3)
        if form == 0:
            body = "\n".join(f"Step {i + 1}: {s}" for i, s in enumerate(steps))
            text = f"{body}\nFinal answer: {final}"
        elif form == 1:
            body = "\n".join(f"- {s}" for s in steps)
            text = f"Here is the calculation:\n{body}\nSo the answer is {final}."
        else:
            text = "Working: " + "; ".join(steps) + f". Answer: {final}"
        return text, final

    request = judge_request(t, p)
    questions, expected = {}, {}
    f: dict[str, Any] = {"template": t, "params": p, "responses": []}
    if variant == "verify":
        correct = plan_correct
        err = None if correct else rng.choice(JUDGE_ERRORS[t])
        text, final = response(err)
        f["responses"].append({"error": err, "final": final})
        state = (f"Request:\n{request}\n\nResponse:\n{text}")
        questions["correct"] = qnoul(rng.choice([
            "Does the response fully and correctly satisfy the request?",
            "Is the response's final answer correct and correctly worked out?",
            "Should this response be accepted as correct?",
        ]), "Yes, it is fully correct", "No, it contains an error")
        expected["correct"] = 1.0 if correct else 0.0
        label: Any = correct
    else:
        k = plan_k
        errs = rng.sample(JUDGE_ERRORS[t], k - 1)
        gold_pos = plan_pos
        order: list[str | None] = list(errs)
        order.insert(gold_pos, None)
        blocks = [f"Request:\n{request}"]
        finals = set()
        for j, err in enumerate(order):
            text, final = response(err)
            if final in finals:
                raise Retry("same_final")
            finals.add(final)
            f["responses"].append({"error": err, "final": final})
            blocks.append(f"Response {'ABC'[j]}:\n{text}")
        state = "\n\n".join(blocks)
        # Keys follow the response order; the gold position is drawn uniformly above.
        questions["best"] = clean_question("choice", rng.choice([
            "Which response fully and correctly satisfies the request?", "Which response is fully correct?",
        ]), {f"response_{'abc'[j]}": f"Response {'ABC'[j]}" for j in range(k)})
        expected["best"] = f"response_{'abc'[gold_pos]}"
        label = expected["best"]
    if long:
        intro = rng.choice([
            "A customer-support assistant answered the following question. Reviewers check every number.",
            "The following exchange was flagged for quality review.",
            "An internal help-desk bot produced the answer below.",
        ])
        notes = filler(rng, [
            "Reviewers should not give credit for a right method with a wrong number.",
            "The user did not reply after receiving the answer.",
            "The assistant's tone was rated as friendly in a separate review.",
            "Formatting differences (currency symbols, spacing) do not matter.",
        ], rng.randint(200, 600))
        state = f"{intro}\n\n{state}\n\nReview notes: {notes}"
    return {"family": "judge", "variant": f"{variant}_{t}", "state": state, "questions": questions, "expected": expected,
                "facts": f, "label": label}


