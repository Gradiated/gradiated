ROSTER_RULES = ("rest", "shift_length", "weekly_cap")


def roster_violations(f: dict[str, Any]) -> list[tuple[datetime, int, str, int]]:
    """Breaches as (instant, rule order, rule, shift index), sorted by instant then rule order."""
    offices = f["offices"]
    shifts = []
    for i, s in enumerate(f["shifts"]):
        z = offices[s["office"]]
        su = to_utc(z, datetime.fromisoformat(s["start"]))
        eu = to_utc(z, datetime.fromisoformat(s["end"]))
        shifts.append((su, eu, i))
    shifts.sort()
    out = []
    rest, max_len, cap = (timedelta(hours=f["min_rest_h"]), timedelta(hours=f["max_shift_h"]),
                          timedelta(hours=f["week_cap_h"]))
    week_total: dict[date, timedelta] = defaultdict(timedelta)
    week_hit: set[date] = set()
    for n, (su, eu, i) in enumerate(shifts):
        if n and su - shifts[n - 1][1] < rest:
            out.append((su, 0, "rest", i))
        if eu - su > max_len:
            out.append((su, 1, "shift_length", i))
        local = su.astimezone(zone(f["home_zone"])).date()
        monday = local - timedelta(days=local.weekday())
        week_total[monday] += eu - su
        if week_total[monday] > cap and monday not in week_hit:
            week_hit.add(monday)
            out.append((su, 2, "weekly_cap", i))
    out.sort(key=lambda v: (v[0], v[1]))
    return out


def roster_label(viol: list, want: str) -> Any:
    if want in ("compliant", "breach"):
        return not viol
    if want.startswith("first:"):
        return viol[0][2] if viol else "none"
    return min(len(viol), 3)


def gen_roster(rng: random.Random, long: bool, want: str, trap: bool = False) -> dict[str, Any]:
    home = rng.choice(DST_CITIES)
    offices = {f"{home} office": CITIES[home]}
    if rng.random() < 0.5:
        second = rng.choice([c for c in CITIES if CITIES[c] != CITIES[home]])
        offices[f"{second} office"] = CITIES[second]
    names = list(offices)
    focus = offices[rng.choice(names)]
    R = rng.choice([10, 11, 12])
    L = rng.choice([8, 9, 10, 12])
    W = rng.choice([36, 38, 40, 42, 45, 48])
    d = date_near_dst(rng, focus, before=4, after=1)
    pattern = rng.choice(["day", "night", "mixed", "night"])
    n = rng.randint(4, 9)
    office = names[0]
    shifts = []
    for i in range(n):
        if len(names) > 1 and rng.random() < 0.3:
            office = names[1 - names.index(office)]
        if i:
            d += timedelta(days=rng.choices([1, 2, 3], [0.72, 0.2, 0.08])[0])
        p = pattern if pattern != "mixed" else rng.choice(["day", "late", "night"])
        h = {"day": rng.randint(5, 10), "late": rng.randint(12, 16), "night": rng.randint(19, 23)}[p]
        start = datetime.combine(d, time(h, rng.choice([0, 15, 30, 45])))
        r = rng.random()
        if r < 0.2:
            minutes = L * 60
        elif r < 0.26:
            minutes = L * 60 + 60
        elif r < 0.3:
            minutes = L * 60 + 15 * rng.randint(1, 4)
        else:
            minutes = 15 * rng.randint(max(16, (L - 4) * 4), L * 4 - 1)
        end = start + timedelta(minutes=minutes)
        z = offices[office]
        aware(z, start)
        aware(z, end)
        shifts.append({"office": office, "start": start.isoformat(timespec="minutes"),
                       "end": end.isoformat(timespec="minutes")})
    f = {"home_zone": offices[names[0]], "home_office": names[0], "offices": offices, "min_rest_h": R,
         "max_shift_h": L, "week_cap_h": W, "shifts": shifts}
    # Shifts must not overlap (a roster with overlapping shifts is a data error, not a rest breach).
    spans = sorted((to_utc(offices[s["office"]], datetime.fromisoformat(s["start"])),
                    to_utc(offices[s["office"]], datetime.fromisoformat(s["end"]))) for s in shifts)
    if any(spans[k][0] < spans[k - 1][1] + timedelta(hours=2) for k in range(1, len(spans))):
        raise Retry("overlap")
    viol = roster_violations(f)
    first = viol[0][2] if viol else "none"
    count = len(viol)
    if trap:  # the label must change when time zones and clock changes are ignored (wall-clock arithmetic)
        naive = dict(f, home_zone="UTC", offices={k: "UTC" for k in offices})
        if roster_label(roster_violations(naive), want) == roster_label(viol, want):
            raise Retry("no_trap")
    if want in ("compliant", "breach"):
        if (want == "compliant") != (count == 0):
            raise Retry("want")
    elif want.startswith("first:"):
        if first != want[6:]:
            raise Retry("want")
    elif want.startswith("count:"):
        if min(count, 3) != int(want[6:]):
            raise Retry("want")
    return f


