def gen_policy_facts(rng: random.Random) -> dict[str, Any]:
    domain = rng.choice(["relocation", "rebate"])
    year = rng.randint(2025, 2028)
    app = date(year, rng.randint(1, 12), rng.randint(1, 28))
    if domain == "relocation":
        th = {"tenure": rng.choice([6, 12, 18, 24]), "distance": rng.choice([40, 50, 60, 80]),
              "timing": rng.choice([60, 90, 120]), "income": rng.choice([60, 75, 90, 120]) * 1000}
        cond = rng.choice(list(th))
        new = {"tenure": rng.choice([3, 6, 9, 12, 18]), "distance": rng.choice([30, 40, 45, 70]),
               "timing": rng.choice([45, 60, 150, 180]), "income": rng.choice([55, 70, 85, 100, 140]) * 1000}[cond]
        if new == th[cond]:
            raise Retry("same")
        am = {"condition": cond, "value": new,
              "effective": None if rng.random() < 0.25 else (app + timedelta(days=rng.randint(-40, 40))).isoformat()}
        eff = dict(th)
        if am["effective"] is None or app >= date.fromisoformat(am["effective"]):
            eff[cond] = new
        tenure_m = eff["tenure"] + rng.choice([-1, 0, 0, 1, 2, rng.randint(-6, 12)])
        hire = add_months(app, -max(1, tenure_m)) + timedelta(days=rng.choice([-2, -1, 0, 0, 1, 2]))
        if rng.random() < 0.4:
            km = Fraction(eff["distance"] + rng.choice([-6, -3, -1, 0, 1, 2, 5, 15]))
            dist, unit = str(km), "km"
        else:
            miles = Fraction(eff["distance"] + rng.choice([-5, -2, 0, 1, 3, 8]), 1) / Fraction(1609344, 1000000)
            dist, unit = dec(miles, 1), "miles"
        start = app - timedelta(days=eff["timing"] + rng.choice([-20, -5, -1, 0, 1, 3, 12]))
        tens = (eff["income"] + rng.choice([-1, 1]) * rng.randint(0, 6000)) // 10  # income in whole units
        n = rng.randint(2, 4)
        names = rng.sample(["Applicant salary", "Partner salary", "Rental income", "Freelance income",
                            "Pension", "Child benefit"], n)
        parts = sorted(rng.sample(range(1, tens), n - 1))
        items = [[nm, (b - a) * 10] for nm, a, b in zip(names, [0] + parts, parts + [tens])]
        if any(v <= 0 for _, v in items):
            raise Retry("item")
        return {"domain": domain, "application_date": app.isoformat(), "thresholds": th, "amendment": am,
                "hire_date": hire.isoformat(), "distance": dist, "distance_unit": unit, "start_date": start.isoformat(),
                "income_items": items}
    th = {"size": rng.choice([10, 20, 25, 50]), "timing": rng.choice([60, 90, 180]),
          "cost": rng.choice([5, 8, 10, 15]) * 1000 * 100, "turnover": rng.choice([500, 1000, 2000]) * 1000}
    cond = rng.choice(list(th))
    new = {"size": rng.choice([15, 30, 40]), "timing": rng.choice([30, 120, 365]),
           "cost": rng.choice([3, 6, 12, 20]) * 1000 * 100, "turnover": rng.choice([750, 1500, 3000]) * 1000}[cond]
    if new == th[cond]:
        raise Retry("same")
    am = {"condition": cond, "value": new,
          "effective": None if rng.random() < 0.25 else (app + timedelta(days=rng.randint(-40, 40))).isoformat()}
    eff = dict(th)
    if am["effective"] is None or app >= date.fromisoformat(am["effective"]):
        eff[cond] = new
    fte_target = eff["size"] + rng.choice([-2, -1, -0.5, 0, 0, 0.5, 1, 3])
    pt = rng.randint(0, 10)
    ft = int(fte_target - pt / 2)
    if ft < 1:
        raise Retry("ft")
    inst = app - timedelta(days=eff["timing"] + rng.choice([-30, -3, -1, 0, 1, 2, 10]))
    vat = rng.choice(["20", "19", "21", "10"])
    net_target = eff["cost"] + rng.choice([-1, 1]) * rng.randint(0, 800) * 100
    gross_total = round_half_up(Fraction(net_target) * (100 + frac(vat)) / 100)
    n = rng.randint(1, 3)
    cuts = sorted(rng.sample(range(1, gross_total), n - 1)) if n > 1 else []
    gross = [b - a for a, b in zip([0] + cuts, cuts + [gross_total])]
    equipment = [[nm, g] for nm, g in zip(rng.sample(["Heat pump unit", "Installation labour", "Smart thermostat",
                                                       "LED retrofit", "Insulation panels"], n), gross)]
    tt = eff["turnover"] + rng.choice([-1, 1]) * rng.randint(0, 40000)
    qs = [tt // 4 + rng.randint(-20000, 20000) for _ in range(3)]
    qs.append(tt - sum(qs))
    if min(qs) <= 0:
        raise Retry("q")
    return {"domain": domain, "application_date": app.isoformat(), "thresholds": th, "amendment": am,
            "full_time": ft, "part_time": pt, "install_date": inst.isoformat(), "vat_pct": vat,
            "equipment": equipment, "turnover": [[f"Q{i + 1}", v] for i, v in enumerate(qs)]}


