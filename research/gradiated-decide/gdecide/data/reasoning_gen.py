THRESHOLD_CLASSES = ("pass", "narrow_fail", "clear_fail")


def threshold_corrected(meas: str, unit: str, unc: dict[str, str], kind: str, bug: str | None = None) -> Fraction:
    """Corrected value as a mass fraction (canonical units)."""
    m = frac(meas)
    if bug == "correction_omitted":
        u = Fraction(0)
    elif unc["kind"] == "abs":
        u = frac(unc["value"])
    elif bug == "relative_as_absolute":
        u = frac(unc["pct"])
    else:
        u = m * frac(unc["pct"]) / 100
    sign = 1 if kind == "max" else -1
    if bug == "wrong_sign":
        sign = -sign
    return (m + sign * u) * UNIT_FACTOR[unit]


def threshold_class(f: dict[str, Any], meas: str, bug: str | None = None) -> str:
    c = threshold_corrected(meas, f["meas_unit"], f["uncertainty"], f["limit_kind"], bug)
    lim = frac(f["limit"]) * UNIT_FACTOR[f["limit_unit"]]
    margin = lim * frac(f["narrow_pct"]) / 100
    if f["limit_kind"] == "max":
        ok = c < lim or (f["equal_passes"] and c == lim)
        excess = c - lim
    else:
        ok = c > lim or (f["equal_passes"] and c == lim)
        excess = lim - c
    if ok:
        return "pass"
    return "narrow_fail" if excess <= margin else "clear_fail"


def sig_places(value: Fraction, sig: int = 3) -> int:
    if value <= 0:
        return 2
    return max(0, sig - 1 - math.floor(math.log10(float(value))))


def make_measurement(rng: random.Random, f: dict[str, Any], target: str) -> str:
    """A measured value (string in the measurement unit) whose class is ``target``."""
    lim_c = frac(f["limit"]) * UNIT_FACTOR[f["limit_unit"]]
    lim_m = lim_c / UNIT_FACTOR[f["meas_unit"]]  # limit in measurement units
    m_pct = frac(f["narrow_pct"]) / 100
    unc = f["uncertainty"]
    sign = 1 if f["limit_kind"] == "max" else -1
    places = sig_places(lim_m, rng.choice([3, 3, 4]))
    if unc["kind"] == "abs":
        places = max(places, len(unc["value"].split(".")[1]) if "." in unc["value"] else 0)
    # For failing targets, prefer values that pass when the correction is forgotten (the typical mistake).
    trap = target != "pass" and rng.random() < 0.6
    for attempt in range(300):
        r = rng.random()
        if target == "pass":
            if f["equal_passes"] and r < 0.25:
                corrected = lim_m
            else:
                corrected = lim_m * (1 - sign * Fraction(rng.randint(2, 350), 1000))
        elif target == "narrow_fail":
            if not f["equal_passes"] and r < 0.2:
                corrected = lim_m
            elif r < 0.35:
                corrected = lim_m * (1 + sign * m_pct)
            else:
                corrected = lim_m * (1 + sign * m_pct * Fraction(rng.randint(5, 995), 1000))
        else:
            corrected = lim_m * (1 + sign * (m_pct + Fraction(rng.randint(1, 600), 1000)))
        if unc["kind"] == "abs":
            measured = corrected - sign * frac(unc["value"])
        else:
            measured = corrected / (1 + sign * frac(unc["pct"]) / 100)
        if measured <= 0:
            continue
        text = dec(measured, places)
        if frac(text) <= 0:
            continue
        if threshold_class(f, text) == target:
            if trap and attempt < 200 and threshold_class(f, text, "correction_omitted") == target:
                continue
            return text
    raise Retry("measurement")


def fmt_unit_value(text: str, unit: str) -> str:
    return f"{text}%" if unit == "%" else f"{text} {unit}"


def gen_threshold(rng: random.Random, long: bool, pseed: int) -> dict[str, Any]:
    plan = random.Random(pseed)  # variant and target label: fixed across retries
    product, analyte, kind, lunit, limits, munits, liquid = rng.choice(THRESHOLD_SCENARIOS)
    munit = rng.choice(munits)
    limit = rng.choice(limits)
    lim_m = frac(limit) * UNIT_FACTOR[lunit] / UNIT_FACTOR[munit]
    if rng.random() < 0.5:
        places = sig_places(lim_m, 2)
        val = lim_m * Fraction(rng.choice([3, 4, 5, 6, 8, 10, 12, 15]), 100)
        unc = {"kind": "abs", "value": plain(Decimal(dec(val, places)))}
        if frac(unc["value"]) <= 0:
            raise Retry("unc_zero")
    else:
        unc = {"kind": "rel", "pct": rng.choice(["5", "8", "10", "12", "15", "20", "25"])}
    f: dict[str, Any] = {"product": product, "analyte": analyte, "limit_kind": kind, "limit": limit,
                         "limit_unit": lunit, "meas_unit": munit, "uncertainty": unc,
                         "equal_passes": rng.random() < 0.5, "narrow_pct": rng.choice(["5", "10", "20", "25"]),
                         "liquid": liquid, "samples": []}
    variant = plan.choices(["band", "complies", "corrected", "count"], weights=[3, 3, 2, 2])[0]
    style_lab = rng.choice(["Lot", "Batch", "Sample"])
    questions, expected = {}, {}
    if variant in ("band", "complies", "corrected"):
        if variant == "complies":
            target = "pass" if plan.random() < 0.5 else plan.choice(["narrow_fail", "clear_fail"])
        else:
            target = plan.choice(THRESHOLD_CLASSES)
        meas = make_measurement(rng, f, target)
        name = f"{style_lab} {rng.randint(100, 999)}-{rng.choice('ABCDEFGHK')}"
        f["samples"].append({"name": name, "measured": meas})
        if variant == "band":
            questions["result"] = qchoice(rng, rng.choice([
                f"How is {name} classified?", f"Classify the {analyte} result for {name}.",
                f"Which outcome applies to {name} under the assessment rules?",
            ]), [("pass", "Pass (complies with the limit)"), ("narrow_fail", "Narrow fail"),
                 ("clear_fail", "Clear fail")])
            expected["result"] = target
            label: Any = target
        elif variant == "complies":
            questions["complies"] = qnoul(rng.choice([
                f"Does {name} comply with the {analyte} limit?", f"Can {name} be released as compliant?",
                f"After the conservative correction, does {name} meet the limit?",
            ]), "Yes, it complies", "No, it fails (narrowly or clearly)")
            expected["complies"] = 1.0 if target == "pass" else 0.0
            label = target == "pass"
        else:
            lp = max(sig_places(frac(limit), 4), 2)

            def val_opt(bug):
                c = threshold_corrected(meas, munit, unc, kind, bug) / UNIT_FACTOR[lunit]
                s = plain(Decimal(dec(c, lp)))
                return ("v_" + s.replace(".", "_").replace("-", "minus_"), fmt_unit_value(s, lunit)), c
            gold_opt, gold_c = val_opt(None)
            wrong, extra = [], []
            for bug in ("correction_omitted", "wrong_sign", "relative_as_absolute"):
                if bug == "relative_as_absolute" and unc["kind"] != "rel":
                    continue
                opt, c = val_opt(bug)
                if c != gold_c:
                    wrong.append(opt)
            for factor in (Fraction(1000), Fraction(1, 1000), Fraction(10), Fraction(1, 10)):
                c = gold_c * factor
                s = plain(Decimal(dec(c, lp + 3 if factor < 1 else lp)))
                if frac(s) > 0:
                    extra.append(("v_" + s.replace(".", "_"), fmt_unit_value(s, lunit)))
            opts = fill_options(rng, gold_opt, wrong, extra)
            gold_v = frac(gold_opt[1].split()[0].rstrip("%"))
            for o in opts[1:]:  # a wrong option within rounding distance of gold would be unfair
                if abs(frac(o[1].split()[0].rstrip("%")) - gold_v) <= max(abs(gold_v) / 200, Fraction(1, 10**lp)):
                    raise Retry("option_values_too_close")
            questions["corrected"] = qchoice(rng, rng.choice([
                f"Which corrected value, in {lunit}, is compared with the limit for {name}?",
                f"After the conservative correction, what is the {analyte} value of {name} expressed in {lunit} "
                f"(rounded to {lp} decimals)?",
            ]), opts)
            expected["corrected"] = gold_opt[0]
            label = gold_opt[0]
    else:
        k = plan.randint(3, 5)
        count = plan.randint(0, k)
        targets = ["pass"] * count + [rng.choice(["narrow_fail", "clear_fail"]) for _ in range(k - count)]
        rng.shuffle(targets)
        base = rng.randint(100, 900)
        for j, t in enumerate(targets):
            f["samples"].append({"name": f"{style_lab} {base + j}", "measured": make_measurement(rng, f, t)})
        questions["count_pass"] = qscore(rng.choice([
            f"How many of the {k} {style_lab.lower()}s comply with the limit?",
            f"Count the {style_lab.lower()}s that pass after the conservative correction.",
        ]), [f"{i} of {k}" for i in range(k + 1)])
        expected["count_pass"] = str(count)
        label = count
    # ---- text
    lim_text = fmt_unit_value(limit, lunit)
    rules = [
        f"Limit: {analyte} in {product} must be {'at most' if kind == 'max' else 'at least'} {lim_text}"
        + (" (inclusive: a corrected value exactly at the limit complies)." if f["equal_passes"]
           else f" and a corrected value exactly at the limit does not comply (it must be strictly "
                f"{'below' if kind == 'max' else 'above'})."),
    ]
    if unc["kind"] == "abs":
        utext = f"the expanded measurement uncertainty of {fmt_unit_value(unc['value'], munit)}"
    else:
        utext = f"the expanded measurement uncertainty ({unc['pct']}% of the measured value)"
    rules.append(f"Conservative assessment: {utext} is {'added to' if kind == 'max' else 'subtracted from'} the "
                 f"measured value before comparison with the limit.")
    rules.append(f"A non-compliant result is a narrow fail if the corrected value is no more than {f['narrow_pct']}% "
                 f"of the limit {'above' if kind == 'max' else 'below'} it; otherwise it is a clear fail.")
    if liquid and (munit in LIQUID_UNITS or lunit in LIQUID_UNITS) and munit != lunit:
        rules.append("For unit conversion, 1 L of sample weighs 1 kg (so 1 mg/L = 1 ppm = 1 mg/kg).")
    elif munit in ("ppm", "ppb") or lunit in ("ppm", "ppb"):
        rules.append("ppm and ppb are by mass.")
    results = [f"{s['name']}: measured {fmt_unit_value(s['measured'], munit)}." for s in f["samples"]]
    head = rng.choice([
        f"Laboratory report: {analyte} in {product}.",
        f"Release check for {product} ({rng.choice(FIRMS)}).",
        f"Quality control of {product}: {analyte}.",
    ])
    specific = [
        "The method's limit of quantification is far below the values reported here.",
        f"Samples were stored at {rng.randint(2, 8)} °C before analysis.",
        f"A previous lot from the same supplier measured "
        f"{fmt_unit_value(plain(Decimal(dec(lim_m * Fraction(rng.randint(40, 90), 100), 3))), munit)}.",
        f"The analyst was {rng.choice(PEOPLE)}; results were reviewed by a second analyst.",
        "The laboratory is accredited for this method.",
        "Results are reported as received, not on a dry-matter basis.",
    ]
    state = assemble(rng, ["Assessment rules:\n" + "\n".join("- " + r for r in rules),
                           "Results:\n" + "\n".join(results)], long, specific, head)
    return {"family": "threshold", "variant": variant, "state": state, "questions": questions, "expected": expected, "facts": f,
                "label": label}


